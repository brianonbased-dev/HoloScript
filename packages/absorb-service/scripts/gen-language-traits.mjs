#!/usr/bin/env node
/**
 * gen-language-traits.mjs — generate LANGUAGE_TRAITS from the native @language_adapter
 * .holo declarations. This closes the native-authoring split the founder flagged
 * (2026-07-03: "HoloScript formats make the product like absorb"): a language adapter is
 * AUTHORED as `language-adapters/<lang>.holo` (@language_adapter data), and this TS is a
 * pure build ARTIFACT — the hand-duplicated RUBY_TRAIT is deleted. Adding/editing a language
 * = edit a .holo, regenerate. D.104 (TS dissolving into native), mirrors check-language-registry.mjs.
 *
 *   node scripts/gen-language-traits.mjs           # (re)write src/engine/adapters/language-traits.generated.ts
 *   node scripts/gen-language-traits.mjs --check    # exit 1 if the generated file is stale vs the .holo sources
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const declarationsDir = resolve(pkgRoot, 'language-adapters');
const outPath = resolve(pkgRoot, 'src', 'engine', 'adapters', 'language-traits.generated.ts');
const check = process.argv.includes('--check');

const parseHolo = await (async () => {
  try { return (await import('@holoscript/core/parser')).parseHolo; }
  catch { return (await import('../../core/src/parser/HoloCompositionParser.ts')).parseHolo; }
})();

function stripGrammarVersion(spec) {
  if (typeof spec !== 'string') return spec;
  const at = spec.indexOf('@', spec.startsWith('@') ? 1 : 0);
  return at === -1 ? spec : spec.slice(0, at);
}

function listHolo(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => f.endsWith('.holo')).sort().map((f) => resolve(dir, f));
}

function loadTraits() {
  const traits = [];
  for (const file of listHolo(declarationsDir)) {
    const parsed = parseHolo(readFileSync(file, 'utf8'), { tolerant: false });
    if (!parsed.success || !parsed.ast) {
      throw new Error(`${file}: failed to parse: ${(parsed.errors || []).map((e) => e.message).join('; ')}`);
    }
    for (const trait of parsed.ast.traits || []) {
      if (trait.name !== 'language_adapter') continue;
      const c = trait.config || {};
      if (!c.language) throw new Error(`${file}: @language_adapter.language required`);
      traits.push({
        language: c.language,
        extensions: c.extensions || [],
        grammarPackage: stripGrammarVersion(c.grammarPackage ?? c.grammar),
        symbols: c.symbols || [],
        imports: c.imports || undefined,
        pathImports: c.pathImports || undefined,
        moduleImports: c.moduleImports || undefined,
        useImports: c.useImports || undefined,
        clauseImports: c.clauseImports || undefined,
        calls: c.calls || undefined,
        eventSites: c.eventSites || undefined,
        callerScope: c.callerScope || undefined,
        visibilityFromModifier: c.visibilityFromModifier || undefined,
      });
    }
  }
  traits.sort((a, b) => a.language.localeCompare(b.language));
  return traits;
}

function render(traits) {
  const body = traits.map((t) => '  ' + JSON.stringify(t)).join(',\n');
  return `// @generated by scripts/gen-language-traits.mjs from language-adapters/*.holo — DO NOT EDIT.
// Native-authoring (D.104, founder 2026-07-03): a language adapter is AUTHORED as a .holo
// @language_adapter declaration; this file is a build artifact. Add/edit a language by editing
// the .holo and running \`pnpm --filter @holoscript/absorb-service generate:language-traits\`.
import type { LanguageTrait } from './language-traits';

export const LANGUAGE_TRAITS: LanguageTrait[] = [
${body},
];
`;
}

const expected = render(loadTraits());
if (check) {
  const actual = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (actual !== expected) {
    console.error('[language-traits] STALE — run `pnpm --filter @holoscript/absorb-service generate:language-traits`');
    process.exit(1);
  }
  console.log('[language-traits] in sync with .holo declarations.');
} else {
  writeFileSync(outPath, expected, 'utf8');
  const n = (expected.match(/"language":/g) || []).length;
  console.log(`[language-traits] wrote ${n} language trait(s) from .holo -> language-traits.generated.ts`);
}
