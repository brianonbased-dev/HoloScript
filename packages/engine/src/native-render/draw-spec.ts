/**
 * draw-spec — pure-data scene extraction for the native render path (D.083, task 2h3s).
 *
 * The PRE-MORTEM verdict: `ECSWorld → IDrawCall[]` is NOT a connector — IDrawCall is
 * GPU-resource-bound (GPUBuffer vertex data, GPUBindGroup material) and requires a live
 * GPUDevice. So this module is deliberately the GPU-FREE half: it extracts pure data
 * (geometry kind + params, material values, model matrix) from the canonical engine VM
 * world. It is headless-unit-testable (no `navigator.gpu`, no Three.js) and is the only
 * part that belongs in CI. The GPU resource builder (DrawSpec[] + GPUDevice → IDrawCall[])
 * is a SEPARATE, additive, opt-in backend gated on a browser-run receipt — NOT here.
 *
 * Imports only the engine VM's own world/types — zero foreign-engine imports.
 */

import {
  ECSWorld,
  type TransformComponent,
  type GeometryComponent,
  type MaterialComponent,
} from '../vm/executor';
import { ComponentType, GeometryType } from '../vm/opcodes';

// ---------------------------------------------------------------------------
// Normalise Vec3/Quat — the ECSWorld stores tuples ([x,y,z]) but callers
// sometimes pass object-form ({x,y,z}). Accept either.
// ---------------------------------------------------------------------------

type Vec3Like = { x: number; y: number; z: number } | [number, number, number] | readonly number[];
type QuatLike =
  | { x: number; y: number; z: number; w: number }
  | [number, number, number, number]
  | readonly number[];

function vec3(v: Vec3Like): { x: number; y: number; z: number } {
  if (
    Array.isArray(v) ||
    ((v as readonly number[]).length !== undefined &&
      typeof (v as readonly number[])[0] === 'number')
  ) {
    const a = v as readonly number[];
    return { x: a[0] ?? 0, y: a[1] ?? 0, z: a[2] ?? 0 };
  }
  const o = v as { x: number; y: number; z: number };
  return { x: o.x ?? 0, y: o.y ?? 0, z: o.z ?? 0 };
}

function quat(q: QuatLike): { x: number; y: number; z: number; w: number } {
  if (
    Array.isArray(q) ||
    ((q as readonly number[]).length !== undefined &&
      typeof (q as readonly number[])[0] === 'number')
  ) {
    const a = q as readonly number[];
    return { x: a[0] ?? 0, y: a[1] ?? 0, z: a[2] ?? 0, w: a[3] ?? 1 };
  }
  const o = q as { x: number; y: number; z: number; w: number };
  return { x: o.x ?? 0, y: o.y ?? 0, z: o.z ?? 0, w: o.w ?? 1 };
}

export type GeometryKind =
  | 'cube'
  | 'sphere'
  | 'cylinder'
  | 'plane'
  | 'cone'
  | 'torus'
  | 'capsule'
  | 'mesh'
  | 'unknown';

/** Pure-data reference to a texture map — either the ENCODED image bytes (e.g. PNG/JPEG, as
 *  embedded in a glTF image bufferView) + MIME type, or an external URI. No decoded pixels and
 *  no GPU resources: a later stage / the GPU backend decodes + uploads. (Track 0: the `.holo`
 *  material IR can carry a real imported texture map, not only packed scalars.) */
export interface TextureRef {
  /** Encoded image bytes (e.g. PNG/JPEG) when embedded in the source (glTF image bufferView). */
  bytes?: Uint8Array<ArrayBuffer>;
  /** MIME type of `bytes` (e.g. 'image/png', 'image/jpeg'). */
  mimeType?: string;
  /** External URI when the source references the image by path instead of embedding it. */
  uri?: string;
}

/** Optional PBR texture maps (glTF model): base color, tangent-space normal, the glTF-combined
 *  metallic-roughness map, and emissive. All optional — absence = the scalar-only material. */
export interface MaterialTextureMaps {
  albedoMap?: TextureRef;
  normalMap?: TextureRef;
  metalRoughMap?: TextureRef;
  emissiveMap?: TextureRef;
}

/** Pure-data material (no GPUBindGroup) — the GPU backend resolves this to a pipeline+bind group. */
export interface MaterialSpec {
  color: number; // packed 0xRRGGBB
  metalness: number;
  roughness: number;
  emissive: number;
  opacity: number;
  /** Optional PBR texture maps populated by the glTF importer; undefined for the procedural /
   *  scalar-only material (existing path byte-for-byte untouched when omitted). */
  albedoMap?: TextureRef;
  normalMap?: TextureRef;
  metalRoughMap?: TextureRef;
  emissiveMap?: TextureRef;
}

/** Pure-data draw specification. NO GPU resources — see module header. */
export interface DrawSpec {
  entityId: number;
  geometry: {
    kind: GeometryKind;
    params: Record<string, number>;
    /**
     * Real imported vertex buffers — present when kind === 'mesh' and a real mesh
     * was carried through the glTF importer (Track-0 / D.101/ssja). Absent for
     * procedural primitives (cube/sphere/…) whose CPU geometry is generated by
     * primitiveToMesh at render time. When present, a native render path can upload
     * positions/indices directly without the original GLB file.
     */
    meshData?: SkinnedMeshData;
  };
  material: MaterialSpec;
  /** Column-major 4x4 model matrix (TRS), 16 floats. */
  modelMatrix: Float32Array;
}

/**
 * Skinned mesh geometry as pure data (no GPU). One palette (bone) index + one weight per
 * vertex — rigid per-bone linear-blend skinning for the procedural body; a future glTF/VRM
 * importer can populate up to 4 influences by extending these to be stride-N.
 */
export interface SkinnedMeshData {
  // Typed as <ArrayBuffer> (not ArrayBufferLike) so they satisfy GPUAllowSharedBufferSource
  // at device.queue.writeBuffer — matches PrimitiveMesh in primitive-mesh.ts.
  positions: Float32Array<ArrayBuffer>;
  normals: Float32Array<ArrayBuffer>;
  /** 4 floats/vertex: xyz strand-flow tangent (Kajiya-Kay) + w = strandT (0 root → 1 tip).
   *  Body verts carry a placeholder (0,1,0,0); only hair/anisotropic materials read it. */
  tangents: Float32Array<ArrayBuffer>;
  /** Optional UV coordinates, 2 floats/vertex (glTF TEXCOORD_0). Populated by the glTF
   *  importer when the source primitive carries texture coordinates; undefined for the
   *  procedural body (which has no UVs). Prerequisite for textured / material-mapped imported
   *  meshes — Track 0: the `.holo` mesh IR carries a real imported surface, not a text pointer. */
  uvs?: Float32Array<ArrayBuffer>;
  indices: Uint32Array<ArrayBuffer>;
  jointIndices: Uint32Array<ArrayBuffer>;
  jointWeights: Float32Array<ArrayBuffer>;
  vertexCount: number;
}

/**
 * Pure-data CHARACTER draw spec — kept SEPARATE from the primitive `DrawSpec` so the
 * existing primitive render path is untouched (premortem regression guard). The native
 * WebGPU character renderer uploads the mesh + the per-frame joint-matrix palette and skins
 * on-GPU. `jointMatrices` = jointCount × 16 column-major floats (skin = worldPose · invBind).
 */
export interface CharacterDrawSpec {
  entityId: string;
  mesh: SkinnedMeshData;
  jointMatrices: Float32Array<ArrayBuffer>;
  jointCount: number;
  /** Required fallback material applied to the whole mesh when `materialGroups` is absent. */
  material: MaterialSpec;
  /** Column-major 4x4 root placement matrix (world position/orientation of the figure). */
  modelMatrix: Float32Array;
  /**
   * Optional per-region materials (glTF-primitive model): contiguous index sub-ranges, each
   * drawn with its own shading pipeline in the SAME render pass + shared skin palette. When
   * present and non-empty, used INSTEAD of `material` (which stays the single-draw fallback —
   * the existing path is byte-for-byte preserved when this is omitted).
   */
  materialGroups?: MaterialGroup[];
}

// ---------------------------------------------------------------------------
// Character material system — additive over the primitive MaterialSpec.
// ---------------------------------------------------------------------------

/** Which fragment shading model a material group renders with. */
export type ShadingModel =
  | 'lambert'
  | 'skin-sss'
  | 'marschner-hair'
  | 'refractive-eye'
  | 'woven-cloth';

/** Flat two-sided half-Lambert (the Phase-0 base; the single-material fallback). */
export interface BaseMaterialSpec extends MaterialSpec {
  shadingModel: 'lambert';
}

/** Single-pass real-time skin: per-channel wrap diffuse + scatter tint + transmission + Fresnel. */
export interface SkinSSSMaterialSpec extends MaterialSpec {
  shadingModel: 'skin-sss';
  /** Subsurface tint, RGB 0..1 (reddish for skin). */
  scatterColor: [number, number, number];
  /** Per-channel relative scatter radius (red widest → leaks furthest past the terminator). */
  scatterRadii: [number, number, number];
  /** Fresnel F0 (skin ≈ 0.028). */
  specularF0: number;
  /** 0 = thin/translucent, 1 = thick/opaque (drives back transmission). */
  thickness: number;
  /** Back-scatter transmission strength. */
  transmitStrength: number;
  /** Ambient floor. */
  ambient: number;
}

/** Kajiya-Kay anisotropic hair with melanin→colour (needs the tangent vertex attribute). */
export interface MarschnerHairMaterialSpec extends MaterialSpec {
  shadingModel: 'marschner-hair';
  melanin: number;
  melaninRedness: number;
  primaryExp: number;
  secondaryExp: number;
}

/** Refractive eye: iris/sclera blend + pupil + wet specular catchlight + Fresnel rim. */
export type RefractiveEyeRegion = 'composite' | 'sclera' | 'iris' | 'pupil' | 'cornea';

export interface RefractiveEyeMaterialSpec extends MaterialSpec {
  shadingModel: 'refractive-eye';
  /** Cornea index of refraction (~1.376) — drives the Fresnel rim strength. */
  ior: number;
  /** Native geometry/material role. Omission preserves the legacy composite eye shader. */
  eyeRegion?: RefractiveEyeRegion;
}

/**
 * Compact local texture tile carried as pure data. Four-by-four texels keep character draw
 * specs deterministic and provider-independent while proving authored UV/material-map flow.
 * Full-resolution imported textures remain the glTF material-map path.
 */
export interface WovenClothTextureTile {
  size: 4;
  /** Sixteen authored luminance values, row-major, multiplied into the base colour. */
  albedo: number[];
  /** Thirty-two authored tangent-space XY values (0..1), row-major pairs. */
  normalXY: number[];
  /** Sixteen authored roughness values, row-major. */
  roughness: number[];
  /** UV repeats over the surface, clamped by the renderer to 1..16. */
  repeat: number;
  /** Tangent-space normal response, 0..2. */
  normalScale: number;
}

/** Rough woven cloth with grazing-angle sheen and optional local UV-mapped material detail. */
export interface WovenClothMaterialSpec extends MaterialSpec {
  shadingModel: 'woven-cloth';
  /** Broad highlight width, 0.05..1. */
  roughness: number;
  /** Retroreflective fibre sheen, 0..1. */
  sheen: number;
  /** World-space weave frequency in cycles/metre. */
  weaveScale: number;
  /** Cloth rim response at grazing angles, 0..1. */
  rimStrength: number;
  /** Optional source-resolved local texture tile sampled through mesh UVs. */
  textureTile?: WovenClothTextureTile;
}

export type CharacterMaterialSpec =
  | BaseMaterialSpec
  | SkinSSSMaterialSpec
  | MarschnerHairMaterialSpec
  | RefractiveEyeMaterialSpec
  | WovenClothMaterialSpec;

/** A contiguous slice of `mesh.indices` drawn with one material. Offsets are INDEX ELEMENTS. */
export interface MaterialGroup {
  /** First index (element offset into mesh.indices) — passed as drawIndexed firstIndex. */
  indexStart: number;
  /** Number of indices in this group. */
  indexCount: number;
  material: CharacterMaterialSpec;
  /** Draw after opaque groups with blend + depthWrite off (e.g. refractive eyes). */
  transparent?: boolean;
}

const GEOMETRY_KIND: Record<number, GeometryKind> = {
  [GeometryType.Cube]: 'cube',
  [GeometryType.Sphere]: 'sphere',
  [GeometryType.Cylinder]: 'cylinder',
  [GeometryType.Plane]: 'plane',
  [GeometryType.Cone]: 'cone',
  [GeometryType.Torus]: 'torus',
  [GeometryType.Capsule]: 'capsule',
  [GeometryType.Mesh]: 'mesh',
};

export function geometryKindFromType(type: number): GeometryKind {
  return GEOMETRY_KIND[type] ?? 'unknown';
}

/**
 * Compose a column-major 4x4 TRS matrix from position / rotation quaternion / scale.
 * Pure math — matches glMatrix fromRotationTranslationScale convention (WGSL column-major).
 */
export function composeTRS(
  t: { x: number; y: number; z: number },
  q: { x: number; y: number; z: number; w: number },
  s: { x: number; y: number; z: number }
): Float32Array {
  const { x, y, z, w } = q;
  const x2 = x + x,
    y2 = y + y,
    z2 = z + z;
  const xx = x * x2,
    xy = x * y2,
    xz = x * z2;
  const yy = y * y2,
    yz = y * z2,
    zz = z * z2;
  const wx = w * x2,
    wy = w * y2,
    wz = w * z2;
  const m = new Float32Array(16);
  m[0] = (1 - (yy + zz)) * s.x;
  m[1] = (xy + wz) * s.x;
  m[2] = (xz - wy) * s.x;
  m[3] = 0;
  m[4] = (xy - wz) * s.y;
  m[5] = (1 - (xx + zz)) * s.y;
  m[6] = (yz + wx) * s.y;
  m[7] = 0;
  m[8] = (xz + wy) * s.z;
  m[9] = (yz - wx) * s.z;
  m[10] = (1 - (xx + yy)) * s.z;
  m[11] = 0;
  m[12] = t.x;
  m[13] = t.y;
  m[14] = t.z;
  m[15] = 1;
  return m;
}

/**
 * Extract pure-data draw specs from the canonical engine VM world. Renderable = alive +
 * has Transform + Geometry + Material. Deterministic order by entity id. NO GPU, NO Three.
 */
export function extractDrawSpecs(world: ECSWorld): DrawSpec[] {
  const specs: DrawSpec[] = [];
  const entities = world
    .getAllEntities()
    .filter((e) => e.alive)
    .sort((a, b) => a.id - b.id);
  for (const e of entities) {
    const t = world.getComponent<TransformComponent>(e.id, ComponentType.Transform);
    const g = world.getComponent<GeometryComponent>(e.id, ComponentType.Geometry);
    const m = world.getComponent<MaterialComponent>(e.id, ComponentType.Material);
    if (!t || !g || !m) continue;
    specs.push({
      entityId: e.id,
      geometry: {
        kind: geometryKindFromType(g.type),
        params: { ...g.params },
        ...(g.meshData ? { meshData: g.meshData } : {}),
      },
      material: {
        color: m.color,
        metalness: m.metalness,
        roughness: m.roughness,
        emissive: m.emissive,
        opacity: m.opacity,
      },
      modelMatrix: composeTRS(
        vec3(t.position as Vec3Like),
        quat(t.rotation as QuatLike),
        vec3(t.scale as Vec3Like)
      ),
    });
  }
  return specs;
}
