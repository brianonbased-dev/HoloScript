import type { R3FNode } from './scene-ir-types';

export interface SceneIRTsxEmitterOptions {
  componentName?: string;
  sourcePath?: string;
  includeCanvas?: boolean;
}

const GENERATED_HEADER = '// @generated by HoloScript SceneIRTsxEmitter -- DO NOT EDIT';
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const INTRINSIC_R3F_TYPES = new Set([
  'group',
  'mesh',
  'ambientLight',
  'directionalLight',
  'pointLight',
  'spotLight',
  'hemisphereLight',
  'rectAreaLight',
]);

export function emitSceneIRTsx(root: R3FNode, options: SceneIRTsxEmitterOptions = {}): string {
  const componentName = sanitizeComponentName(options.componentName ?? root.id ?? 'HoloScene');
  const body = renderNode(root, 2);
  const imports = options.includeCanvas ?? true ? "import { Canvas } from '@react-three/fiber';\n" : '';
  const source = options.sourcePath ? `// source: ${options.sourcePath}\n` : '';

  if (options.includeCanvas === false) {
    return [
      GENERATED_HEADER,
      source.trimEnd(),
      '',
      `export function ${componentName}() {`,
      '  return (',
      body,
      '  );',
      '}',
      '',
      `export default ${componentName};`,
      '',
    ]
      .filter((line, idx) => line !== '' || idx !== 1)
      .join('\n');
  }

  return [
    GENERATED_HEADER,
    source.trimEnd(),
    imports.trimEnd(),
    `export function ${componentName}() {`,
    '  return (',
    '    <Canvas>',
    indent(body, 3),
    '    </Canvas>',
    '  );',
    '}',
    '',
    `export default ${componentName};`,
    '',
  ]
    .filter((line, idx) => line !== '' || idx !== 1)
    .join('\n');
}

function renderNode(node: R3FNode, level: number): string {
  const component = componentForNode(node.type);
  const props = propsForNode(node);
  const pad = '  '.repeat(level);
  const children = node.children ?? [];

  if (children.length === 0) {
    return `${pad}<${component}${props} />`;
  }

  const childLines = children.map((child) => renderNode(child, level + 1)).join('\n');
  return `${pad}<${component}${props}>\n${childLines}\n${pad}</${component}>`;
}

function componentForNode(type: string): string {
  if (INTRINSIC_R3F_TYPES.has(type)) return type;
  if (/light$/i.test(type) && /^[a-z]/.test(type)) return type;
  return 'group';
}

function propsForNode(node: R3FNode): string {
  const props: string[] = [];
  const spreadProps: Record<string, unknown> = {};

  if (node.id) props.push(`name=${quoteAttr(node.id)}`);

  for (const [key, value] of Object.entries(node.props ?? {})) {
    if (value === undefined || key.startsWith('__')) continue;
    if (key === 'hsType') {
      props.push(`userData={${json({ hsType: value })}}`);
      continue;
    }
    if (IDENTIFIER.test(key)) {
      props.push(`${key}={${json(value)}}`);
    } else {
      spreadProps[key] = value;
    }
  }

  if (node.assetMaturity) {
    spreadProps['data-holoscript-asset-maturity'] = node.assetMaturity;
  }

  if (Object.keys(spreadProps).length > 0) {
    props.push(`{...${json(spreadProps)}}`);
  }

  return props.length ? ' ' + props.join(' ') : '';
}

function sanitizeComponentName(name: string): string {
  const words = name
    .replace(/[^A-Za-z0-9_$]+/g, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  const joined = words.map((word) => word[0]!.toUpperCase() + word.slice(1)).join('');
  const candidate = joined || 'HoloScene';
  return /^[A-Za-z_$]/.test(candidate) ? candidate : `HoloScene${candidate}`;
}

function quoteAttr(value: string): string {
  return JSON.stringify(value);
}

function json(value: unknown): string {
  return JSON.stringify(normalizeValue(value), null, 0).replace(/</g, '\\u003c');
}

function normalizeValue(value: unknown): unknown {
  if (ArrayBuffer.isView(value) && !(value instanceof DataView)) {
    return Array.from(value as unknown as Iterable<number>);
  }
  if (Array.isArray(value)) {
    return value.map((entry) => normalizeValue(entry));
  }
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {};
    for (const [key, entry] of Object.entries(value as Record<string, unknown>)) {
      out[key] = normalizeValue(entry);
    }
    return out;
  }
  return value;
}

function indent(text: string, level: number): string {
  const pad = '  '.repeat(level);
  return text
    .split('\n')
    .map((line) => pad + line.trimStart())
    .join('\n');
}
