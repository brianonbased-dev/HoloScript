import type { R3FNode } from './scene-ir-types';

export interface SceneIRTsxEmitterOptions {
  componentName?: string;
  sourcePath?: string;
  includeCanvas?: boolean;
}

const GENERATED_HEADER = '// @generated by HoloScript SceneIRTsxEmitter -- DO NOT EDIT';

export function emitSceneIRTsx(root: R3FNode, options: SceneIRTsxEmitterOptions = {}): string {
  const componentName = sanitizeComponentName(options.componentName ?? root.id ?? 'HoloScene');
  const sceneConstName = `${componentName}SceneIR`;
  const imports = [
    (options.includeCanvas ?? true) ? "import { Canvas } from '@react-three/fiber';" : '',
    "import { HoloSceneIRRenderer } from '@holoscript/r3f-renderer';",
  ].filter(Boolean);
  const source = options.sourcePath ? `// source: ${options.sourcePath}\n` : '';

  if (options.includeCanvas === false) {
    return [
      GENERATED_HEADER,
      source.trimEnd(),
      ...imports,
      '',
      `const ${sceneConstName} = ${json(root)};`,
      '',
      `export function ${componentName}() {`,
      `  return <HoloSceneIRRenderer node={${sceneConstName}} />;`,
      '}',
      '',
      `export default ${componentName};`,
      '',
    ]
      .filter((line, idx) => line !== '' || idx !== 1)
      .join('\n');
  }

  return [
    GENERATED_HEADER,
    source.trimEnd(),
    ...imports,
    '',
    `const ${sceneConstName} = ${json(root)};`,
    '',
    `export function ${componentName}() {`,
    '  return (',
    '    <Canvas>',
    `      <HoloSceneIRRenderer node={${sceneConstName}} />`,
    '    </Canvas>',
    '  );',
    '}',
    '',
    `export default ${componentName};`,
    '',
  ]
    .filter((line, idx) => line !== '' || idx !== 1)
    .join('\n');
}

function sanitizeComponentName(name: string): string {
  const words = name
    .replace(/[^A-Za-z0-9_$]+/g, ' ')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  const joined = words.map((word) => word[0]!.toUpperCase() + word.slice(1)).join('');
  const candidate = joined || 'HoloScene';
  return /^[A-Za-z_$]/.test(candidate) ? candidate : `HoloScene${candidate}`;
}

function json(value: unknown): string {
  return JSON.stringify(normalizeValue(value), null, 2).replace(/</g, '\\u003c');
}

function normalizeValue(value: unknown): unknown {
  if (ArrayBuffer.isView(value) && !(value instanceof DataView)) {
    return Array.from(value as unknown as Iterable<number>);
  }
  if (Array.isArray(value)) {
    return value.map((entry) => normalizeValue(entry));
  }
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {};
    for (const [key, entry] of Object.entries(value as Record<string, unknown>)) {
      out[key] = normalizeValue(entry);
    }
    return out;
  }
  return value;
}
