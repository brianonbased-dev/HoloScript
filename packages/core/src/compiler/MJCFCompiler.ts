/**
 * HoloScript → MJCF (MuJoCo XML) Compiler
 *
 * Exports HoloScript compositions to MuJoCo MJCF XML for physics simulation.
 * MJCF describes a single kinematic tree under <worldbody>: bodies nest to form
 * the tree, geoms attach to bodies, and joints nested inside a child body connect
 * it to its parent. Consumed by the MuJoCo physics engine.
 *
 * BRIDGE target (closes competitor gaps CG-046, CG-110).
 *
 * Maps:
 *   - Composition → <mujoco> root with one <worldbody>
 *   - Objects → <body> with attribute pose + inline <geom>
 *   - Object joint_type → nested <joint> (revolute→hinge, prismatic→slide, ball→ball, floating→free)
 *   - Environment → <option> gravity + ground plane
 *   - Lights → <light> elements in worldbody
 *
 * MuJoCo conventions applied (NOT a blind SDF copy):
 *   - `size` is HALF-extents for box and HALF-length for cylinder/capsule.
 *   - Transforms are ATTRIBUTES on the body (pos / euler radians), not child elements.
 *   - inertiafromgeom="true" lets us omit explicit <inertial>.
 *
 * @version 1.0.0
 */

import { CompilerBase } from './CompilerBase';
import { ANSCapabilityPath, type ANSCapabilityPathValue } from '@holoscript/core-types/ans';
import type {
  HoloComposition,
  HoloObjectDecl,
  HoloSpatialGroup,
  HoloLight,
  HoloEnvironment,
  HoloValue,
} from '../parser/HoloCompositionTypes';

export interface MJCFCompilerOptions {
  /** Model name */
  modelName?: string;
  /** Simulation timestep (seconds) */
  timestep?: number;
  /** Gravity vector "x y z" (m/s^2) */
  gravity?: [number, number, number];
  /** Physics integrator */
  integrator?: 'Euler' | 'RK4' | 'implicit' | 'implicitfast';
  /** Include a ground plane in the worldbody */
  includeGround?: boolean;
  /** Include scene lights */
  includeScene?: boolean;
  /** Mesh asset path prefix */
  meshPathPrefix?: string;
}

export class MJCFCompiler extends CompilerBase {
  protected readonly compilerName = 'MJCFCompiler';

  protected override getRequiredCapability(): ANSCapabilityPathValue {
    return ANSCapabilityPath.MJCF;
  }

  private options: Required<MJCFCompilerOptions>;
  private lines: string[] = [];
  private indentLevel: number = 0;

  constructor(options: MJCFCompilerOptions = {}) {
    super();
    this.options = {
      modelName: options.modelName || 'holoscript_model',
      timestep: options.timestep ?? 0.002,
      gravity: options.gravity ?? [0, 0, -9.81],
      integrator: options.integrator || 'Euler',
      includeGround: options.includeGround ?? true,
      includeScene: options.includeScene ?? true,
      meshPathPrefix: options.meshPathPrefix || '',
    };
  }

  compile(composition: HoloComposition, agentToken: string, outputPath?: string): string {
    this.validateCompilerAccess(agentToken, outputPath);
    this.lines = [];
    this.indentLevel = 0;

    this.emit('<?xml version="1.0"?>');
    this.emit(`<!-- Auto-generated by HoloScript MJCFCompiler -->`);
    this.emit(
      `<!-- Source: composition "${this.escapeStringValue(composition.name as string, 'TypeScript')}" -->`
    );
    this.emit('');
    this.emit(`<mujoco model="${this.escapeXml(this.options.modelName)}">`);
    this.indentLevel++;

    // Compiler settings — inertiafromgeom lets us omit explicit <inertial>.
    this.emit('<compiler inertiafromgeom="true" eulerseq="xyz"/>');

    // Simulation option (timestep, gravity, integrator).
    const g = this.options.gravity;
    this.emit(
      `<option timestep="${this.options.timestep}" gravity="${g[0]} ${g[1]} ${g[2]}" integrator="${this.options.integrator}"/>`
    );

    // Mesh asset declarations (only when meshes are present).
    this.emitAssets(composition);

    this.emit('<worldbody>');
    this.indentLevel++;

    // Ground plane
    if (this.options.includeGround) {
      this.emitGroundPlane();
    }

    // Scene lights
    if (this.options.includeScene) {
      this.emitSunLight();
      if (composition.lights) {
        for (const light of composition.lights) {
          this.emitLight(light);
        }
      }
    }

    // Objects — nested bodies form the kinematic tree. Objects with a `parent`
    // are emitted inside their parent body; roots are emitted at the worldbody.
    if (composition.objects) {
      const objects = composition.objects;
      const roots = objects.filter((o) => !this.extractParent(o));
      for (const obj of roots) {
        this.emitBody(obj, objects);
      }
    }

    // Spatial groups
    if (composition.spatialGroups) {
      for (const group of composition.spatialGroups) {
        this.emitSpatialGroup(group);
      }
    }

    // v4.2: Domain Blocks (documented as comments — MuJoCo has no direct equivalent)
    this.emitMJCFDomainBlocks(composition);

    this.indentLevel--;
    this.emit('</worldbody>');

    this.indentLevel--;
    this.emit('</mujoco>');

    return this.lines.join('\n');
  }

  private emitAssets(composition: HoloComposition): void {
    const meshes = new Set<string>();
    const collectMeshes = (objs: HoloObjectDecl[] | undefined): void => {
      if (!objs) return;
      for (const obj of objs) {
        const geometry = this.extractGeometry(obj);
        if (geometry.includes('.')) {
          meshes.add(geometry);
        }
      }
    };
    collectMeshes(composition.objects);
    if (composition.spatialGroups) {
      for (const group of composition.spatialGroups) {
        collectMeshes(group.objects);
      }
    }

    if (meshes.size === 0) return;

    this.emit('<asset>');
    this.indentLevel++;
    for (const mesh of meshes) {
      const name = this.sanitizeName(mesh);
      this.emit(
        `<mesh name="${name}" file="${this.options.meshPathPrefix}${this.escapeXml(mesh)}"/>`
      );
    }
    this.indentLevel--;
    this.emit('</asset>');
  }

  private emitMJCFDomainBlocks(composition: HoloComposition): void {
    const domainBlocks = composition.domainBlocks ?? [];
    if (domainBlocks.length === 0) return;

    this.emit('');
    this.emit('<!-- v4.2 Domain Blocks (no direct MJCF equivalent) -->');
    for (const block of domainBlocks) {
      this.emit(
        `<!-- Domain block: ${block.domain}/${block.keyword} "${this.escapeStringValue(block.name as string, 'TypeScript')}" -->`
      );
    }
  }

  // ===== Property extraction helpers =====

  private getEnvProp(env: HoloEnvironment | undefined, key: string): HoloValue | undefined {
    if (!env) return undefined;
    if (Array.isArray(env.properties)) {
      const prop = env.properties.find((p) => p.key === key);
      return prop?.value as HoloValue | undefined;
    } else {
      return (env as unknown as Record<string, HoloValue>)[key];
    }
  }

  private getLightProp<T extends HoloValue>(light: HoloLight, key: string, fallback: T): T {
    if (Array.isArray(light.properties)) {
      const prop = light.properties.find((p) => p.key === key);
      return (prop?.value as T) ?? fallback;
    } else if ((light as unknown as Record<string, unknown>)[key] !== undefined) {
      return (light as unknown as Record<string, unknown>)[key] as T;
    }
    return fallback;
  }

  private getTraitName(trait: string | { name: string }): string {
    return typeof trait === 'string' ? trait : trait.name;
  }

  private hasTrait(obj: HoloObjectDecl, traitName: string): boolean {
    return obj.traits?.some((t) => this.getTraitName(t) === traitName) ?? false;
  }

  private emitGroundPlane(): void {
    // MuJoCo plane geom: size="x-half y-half spacing"; zeros mean an infinite plane.
    this.emit('<geom name="floor" type="plane" size="0 0 0.1" rgba="0.8 0.8 0.8 1"/>');
  }

  private emitSunLight(): void {
    this.emit(
      '<light name="sun" directional="true" pos="0 0 10" dir="-0.5 0.1 -0.9" diffuse="0.8 0.8 0.8" specular="0.2 0.2 0.2"/>'
    );
  }

  private emitLight(light: HoloLight): void {
    const name = this.sanitizeName(light.name || 'light');
    const lightTypeValue =
      light.lightType ||
      (typeof (light as { type?: string }).type === 'string' &&
      ['point', 'directional', 'spot', 'hemisphere', 'ambient', 'area'].includes(
        (light as { type?: string }).type!
      )
        ? ((light as { type?: string }).type as string)
        : undefined);
    const isDirectional = lightTypeValue === 'directional';

    const pos = this.getLightProp(light, 'position', [0, 0, 5]);
    const colorVal = this.getLightProp(light, 'color', '#ffffff');
    const color = this.parseColor(typeof colorVal === 'string' ? colorVal : '#ffffff');
    const intensity = this.getLightProp(light, 'intensity', 1.0);
    const dr = color.r * intensity;
    const dg = color.g * intensity;
    const db = color.b * intensity;

    this.emit(
      `<light name="${name}" directional="${isDirectional}" pos="${pos[0]} ${pos[1]} ${pos[2]}" dir="0 0 -1" diffuse="${dr} ${dg} ${db}" specular="${color.r * 0.3} ${color.g * 0.3} ${color.b * 0.3}"/>`
    );
  }

  /**
   * Emit a body and, recursively, its child bodies (objects whose `parent`
   * names this object). Nested bodies form the MuJoCo kinematic tree.
   */
  private emitBody(obj: HoloObjectDecl, allObjects: HoloObjectDecl[]): void {
    const name = this.sanitizeName(obj.name);

    // Pose as ATTRIBUTES on the body (euler in radians).
    const pos = this.extractPosition(obj);
    const rot = this.extractRotation(obj);
    this.emit(
      `<body name="${name}" pos="${pos[0]} ${pos[1]} ${pos[2]}" euler="${rot[0]} ${rot[1]} ${rot[2]}">`
    );
    this.indentLevel++;

    // Joint NESTED inside the child body IS the connection to its parent.
    // The body tree already encodes parent/child — no explicit names needed.
    if (this.extractParent(obj)) {
      this.emitJoint(obj);
    }

    // Inline geom (with color as rgba attribute).
    this.emitGeometry(obj);

    // Recurse into child bodies.
    const children = allObjects.filter((o) => this.extractParent(o) === obj.name);
    for (const child of children) {
      this.emitBody(child, allObjects);
    }

    this.indentLevel--;
    this.emit('</body>');
    this.emit('');
  }

  private emitSpatialGroup(group: HoloSpatialGroup): void {
    this.emit(
      `<!-- Spatial Group: ${this.escapeStringValue(group.name as string, 'TypeScript')} -->`
    );
    if (group.objects) {
      const roots = group.objects.filter((o) => !this.extractParent(o));
      for (const obj of roots) {
        this.emitBody(obj, group.objects);
      }
    }
  }

  /**
   * Emit an inline self-closing <geom> on the current body.
   * NOTE: MuJoCo `size` is HALF-extents for box and HALF-length for cylinder/capsule.
   */
  private emitGeometry(obj: HoloObjectDecl): void {
    const geometryValue = this.extractGeometry(obj);
    const scale = this.extractScale(obj);
    const rgba = this.extractRgba(obj);

    switch (geometryValue) {
      case 'cube':
      case 'box': {
        // SDF full extent is `scale`; MuJoCo box size is half-extents.
        const h = scale / 2;
        this.emit(`<geom type="box" size="${h} ${h} ${h}"${rgba}/>`);
        break;
      }
      case 'sphere':
        this.emit(`<geom type="sphere" size="${scale / 2}"${rgba}/>`);
        break;
      case 'cylinder': {
        // MuJoCo cylinder size = "radius half-length".
        this.emit(`<geom type="cylinder" size="${scale / 2} ${scale / 2}"${rgba}/>`);
        break;
      }
      case 'plane':
        this.emit(`<geom type="plane" size="${scale / 2} ${scale / 2} 0.1"${rgba}/>`);
        break;
      case 'capsule': {
        // MuJoCo capsule size = "radius half-length".
        this.emit(`<geom type="capsule" size="${scale / 3} ${scale / 2}"${rgba}/>`);
        break;
      }
      default:
        if (geometryValue.includes('.')) {
          const meshName = this.sanitizeName(geometryValue);
          this.emit(`<geom type="mesh" mesh="${meshName}"${rgba}/>`);
        } else {
          const h = scale / 2;
          this.emit(`<geom type="box" size="${h} ${h} ${h}"${rgba}/>`);
        }
    }
  }

  /** Build the ` rgba="r g b a"` attribute string (leading space) for a geom, or ''. */
  private extractRgba(obj: HoloObjectDecl): string {
    const color = this.extractColor(obj);
    if (!color) return '';
    const rgb = this.parseColor(color);
    return ` rgba="${rgb.r} ${rgb.g} ${rgb.b} 1"`;
  }

  private extractPosition(obj: HoloObjectDecl): [number, number, number] {
    const posProp = obj.properties.find((p) => p.key === 'position');
    if (posProp && Array.isArray(posProp.value)) {
      return [
        Number(posProp.value[0]) || 0,
        Number(posProp.value[1]) || 0,
        Number(posProp.value[2]) || 0,
      ];
    }
    return [0, 0, 0];
  }

  private extractRotation(obj: HoloObjectDecl): [number, number, number] {
    const rotProp = obj.properties.find((p) => p.key === 'rotation');
    if (rotProp && Array.isArray(rotProp.value)) {
      return [
        ((Number(rotProp.value[0]) || 0) * Math.PI) / 180,
        ((Number(rotProp.value[1]) || 0) * Math.PI) / 180,
        ((Number(rotProp.value[2]) || 0) * Math.PI) / 180,
      ];
    }
    return [0, 0, 0];
  }

  private extractScale(obj: HoloObjectDecl): number {
    const scaleProp = obj.properties.find((p) => p.key === 'scale');
    if (scaleProp) {
      if (typeof scaleProp.value === 'number') return scaleProp.value;
      if (Array.isArray(scaleProp.value)) return Number(scaleProp.value[0]) || 1;
    }
    return 1;
  }

  private extractColor(obj: HoloObjectDecl): string | undefined {
    const colorProp = obj.properties.find((p) => p.key === 'color');
    return colorProp ? this.getStringValue(colorProp.value) : undefined;
  }

  private extractGeometry(obj: HoloObjectDecl): string {
    const geometryProp = obj.properties.find((p) => p.key === 'geometry');
    return geometryProp ? this.getStringValue(geometryProp.value) : 'box';
  }

  private extractParent(obj: HoloObjectDecl): string | undefined {
    const parentProp = obj.properties.find((p) => p.key === 'parent');
    return parentProp ? this.getStringValue(parentProp.value) : undefined;
  }

  /**
   * Emit a joint NESTED in the child body. The body tree encodes parent/child,
   * so no explicit parent/child names are needed. `fixed` → omit the joint
   * entirely (a MuJoCo body with no joint is rigidly attached to its parent).
   */
  private emitJoint(obj: HoloObjectDecl): void {
    const jointTypeProp = obj.properties.find((p) => p.key === 'joint_type');
    const holoJointType = jointTypeProp ? this.getStringValue(jointTypeProp.value) : 'fixed';
    const mjType = this.mapJointType(holoJointType);
    if (!mjType) return; // fixed → rigid attachment, no <joint>

    const name = this.sanitizeName(obj.name);

    const axisProp = obj.properties.find((p) => p.key === 'axis');
    let axisAttr = '';
    if (mjType === 'hinge' || mjType === 'slide') {
      const axis =
        axisProp && Array.isArray(axisProp.value)
          ? axisProp.value.map((v) => Number(v) || 0).join(' ')
          : '0 0 1';
      axisAttr = ` axis="${axis}"`;
    }

    this.emit(`<joint name="${name}_joint" type="${mjType}" pos="0 0 0"${axisAttr}/>`);
  }

  private mapJointType(holoJointType: string): string | undefined {
    switch (holoJointType) {
      case 'revolute':
        return 'hinge';
      case 'prismatic':
        return 'slide';
      case 'ball':
        return 'ball';
      case 'floating':
        return 'free';
      case 'fixed':
      default:
        return undefined;
    }
  }

  private parseColor(color: string): { r: number; g: number; b: number } {
    if (color.startsWith('#')) {
      const hex = color.slice(1);
      return {
        r: parseInt(hex.slice(0, 2), 16) / 255,
        g: parseInt(hex.slice(2, 4), 16) / 255,
        b: parseInt(hex.slice(4, 6), 16) / 255,
      };
    }
    // Named colors
    const colors: Record<string, { r: number; g: number; b: number }> = {
      red: { r: 1, g: 0, b: 0 },
      green: { r: 0, g: 1, b: 0 },
      blue: { r: 0, g: 0, b: 1 },
      white: { r: 1, g: 1, b: 1 },
      black: { r: 0, g: 0, b: 0 },
      yellow: { r: 1, g: 1, b: 0 },
      cyan: { r: 0, g: 1, b: 1 },
      magenta: { r: 1, g: 0, b: 1 },
    };
    return colors[color.toLowerCase()] || { r: 0.7, g: 0.7, b: 0.7 };
  }

  private emit(line: string): void {
    const indent = '  '.repeat(this.indentLevel);
    this.lines.push(indent + line);
  }

  private sanitizeName(name: string): string {
    return name.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
  }

  private escapeXml(str: string): string {
    return str
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  private getStringValue(value: HoloValue): string {
    if (typeof value === 'string') return value;
    if (typeof value === 'number') return String(value);
    if (typeof value === 'boolean') return String(value);
    return '';
  }
}

export default MJCFCompiler;
