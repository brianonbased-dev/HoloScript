import { describe, expect, it } from 'vitest';
import { runExactTrace } from '../HSIExactTrace';
import {
  compileHSPlusStateMachineToKotlin,
  emitHSIIRStateMachineToKotlin,
  HSIKotlinEmissionError,
} from '../HSIIRKotlinStateMachineEmitter';
import { hsiSha256, type HSIIRDocument } from '../HSIIRTypes';
import { lowerHSPlusProgramToHSIIR } from '../HSPlusHSIIRCompiler';

const SOURCE = `
state_machine Workflow {
  input begin: trigger = false
  input finish: trigger = false
  input denied: bool = false

  initial: idle

  state idle {}
  state active {}
  state complete {}

  idle -> active when begin
  idle -> complete when denied
  active -> idle when denied
  active -> complete when finish
}
`;

function reseal(ir: HSIIRDocument): void {
  const { deterministicDigest: _digest, ...provenance } = ir.provenance;
  ir.provenance.deterministicDigest = hsiSha256({ ...ir, provenance });
}

describe('HSI-IR Kotlin state-machine emitter', () => {
  it('emits a typed Kotlin class from canonical .hsplus through HSI-IR', () => {
    const artifact = compileHSPlusStateMachineToKotlin(SOURCE, {
      className: 'WorkflowMachine',
      packageName: 'net.holoscript.generated',
    });

    expect(artifact).toMatchObject({
      className: 'WorkflowMachine',
      machineName: 'Workflow',
      sourceSurface: 'hsplus',
    });
    expect(artifact.sourceDigest).toMatch(/^sha256:/);
    expect(artifact.irDigest).toMatch(/^sha256:/);
    expect(artifact.code).toContain(
      '// @generated by HoloScript HSIIRKotlinStateMachineEmitter — DO NOT EDIT'
    );
    expect(artifact.code).toContain('package net.holoscript.generated');
    expect(artifact.code).toContain('internal class WorkflowMachine');
    expect(artifact.code).toContain('enum class State(val sourceName: String)');
    expect(artifact.code).toContain('IDLE("idle")');
    expect(artifact.code).toContain('fun fireBegin(): Transition?');
    expect(artifact.code).toContain('fun setDenied(value: Boolean): Transition?');
    expect(artifact.code).toContain(
      '_inputBegin -> Transition("transition:Workflow.idle->active#0", from, State.ACTIVE)'
    );
  });

  it('preserves declaration priority rather than sorting transition ids', () => {
    const ir = lowerHSPlusProgramToHSIIR(SOURCE);
    const machine = ir.machines[0]!;
    machine.transitions[0]!.id = 'transition:z-first';
    machine.transitions[1]!.id = 'transition:a-second';
    reseal(ir);

    const code = emitHSIIRStateMachineToKotlin(ir).code;
    expect(code.indexOf('transition:z-first')).toBeLessThan(code.indexOf('transition:a-second'));
  });

  it('emits one-shot trigger clearing and matches the exact-trace reset semantics', () => {
    const ir = lowerHSPlusProgramToHSIIR(SOURCE);
    const trace = runExactTrace(ir, [
      { kind: 'fire-trigger', machine: 'Workflow', input: 'begin' },
      { kind: 'set-input', machine: 'Workflow', input: 'denied', value: true },
      { kind: 'set-input', machine: 'Workflow', input: 'denied', value: false },
    ]);
    const code = emitHSIIRStateMachineToKotlin(ir).code;

    expect(trace.steps.map((step) => step.transitions[0]?.to ?? null)).toEqual([
      'active',
      'idle',
      null,
    ]);
    expect(trace.final.machineStates).toEqual({ Workflow: 'idle' });
    expect(code).toContain(
      'return try {\n      evaluateTransition()\n    } finally {\n      clearTriggers()\n    }'
    );
    expect(code).toContain('_inputBegin = false');
    expect(code).toContain('_inputFinish = false');
  });

  it('rejects tampered HSI-IR before emitting Kotlin', () => {
    const ir = lowerHSPlusProgramToHSIIR(SOURCE);
    ir.machines[0]!.initialState = 'complete';

    expect(() => emitHSIIRStateMachineToKotlin(ir)).toThrowError(HSIKotlinEmissionError);
    expect(() => emitHSIIRStateMachineToKotlin(ir)).toThrowError(/ir-digest-mismatch/);
  });

  it('rejects an expression the bounded Kotlin adapter cannot preserve', () => {
    const ir = lowerHSPlusProgramToHSIIR(SOURCE);
    ir.machines[0]!.transitions[0]!.guard = {
      kind: 'CallExpression',
      callee: 'sqrt',
      arguments: [{ kind: 'Literal', value: 1 }],
    };
    reseal(ir);

    expect(() => emitHSIIRStateMachineToKotlin(ir)).toThrowError(/unsupported-expression/);
  });

  it('rejects duplicate priorities instead of relying on host sort stability', () => {
    const ir = lowerHSPlusProgramToHSIIR(SOURCE);
    ir.machines[0]!.transitions[1]!.priority = ir.machines[0]!.transitions[0]!.priority;
    reseal(ir);

    expect(() => emitHSIIRStateMachineToKotlin(ir)).toThrowError(/duplicate-priority/);
  });
});
