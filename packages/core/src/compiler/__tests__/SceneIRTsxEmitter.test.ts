import { describe, expect, it } from 'vitest';
import type { R3FNode } from '../scene-ir-types';
import { emitSceneIRTsx } from '../SceneIRTsxEmitter';

describe('SceneIRTsxEmitter', () => {
  it('emits generated TSX from SceneIR', () => {
    const scene: R3FNode = {
      type: 'group',
      id: 'NativeScene',
      props: {},
      children: [
        {
          type: 'mesh',
          id: 'Cube',
          props: { hsType: 'cube', position: [0, 1, 0], color: '#ffcc00' },
        },
      ],
    };

    const tsx = emitSceneIRTsx(scene, { sourcePath: 'scenes/native-scene.holo' });

    expect(tsx).toContain('@generated by HoloScript SceneIRTsxEmitter');
    expect(tsx).toContain("import { Canvas } from '@react-three/fiber';");
    expect(tsx).toContain("import { HoloSceneIRRenderer } from '@holoscript/r3f-renderer';");
    expect(tsx).toContain('// source: scenes/native-scene.holo');
    expect(tsx).toContain('export function NativeScene()');
    expect(tsx).toContain('<Canvas>');
    expect(tsx).toContain('<HoloSceneIRRenderer node={NativeSceneSceneIR} />');
    expect(tsx).toContain('"id": "Cube"');
    expect(tsx).toContain('"position": [');
    expect(tsx).not.toContain('<mesh');
  });

  it('keeps internal compiled props in SceneIR data without hand-emitting JSX', () => {
    const scene: R3FNode = {
      type: 'mesh',
      id: 'Lotus',
      props: {
        hsType: 'plane',
        __compiledMaterial: { shaderChunks: { chunks: ['owned by SceneIR runtime'] } },
      },
    };

    const tsx = emitSceneIRTsx(scene, { includeCanvas: false });

    expect(tsx).toContain('<HoloSceneIRRenderer node={LotusSceneIR} />');
    expect(tsx).toContain('__compiledMaterial');
    expect(tsx).not.toContain('<mesh');
  });
});
