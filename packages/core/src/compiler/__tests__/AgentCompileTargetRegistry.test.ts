import { describe, expect, it } from 'vitest';
import { parseHolo } from '../../parser/HoloCompositionParser';
import type { HoloComposition } from '../../parser/HoloCompositionTypes';
import { getRegisteredCompilerANSName } from '../CompilerBase';
import type { ExportTarget } from '../CircuitBreaker';
import { ExportManager } from '../ExportManager';
import { targetSovereignty } from '../sovereign-targets';
import { readJson } from '../../errors/safeJsonParse';

const AGENT_BRAIN_HSPLUS = `composition "CompileTargetBrain" {
  object "planner_agent" {
    @agent(role: "planner")
    @model(provider: "openai", name: "gpt-4o", temperature: 0.2)
    @system_prompt(text: "Plan safely.")
    @lif_neuron(num_neurons: 8, tau: 12.0, v_threshold: 0.8)
    geometry: "cube"
    position: [0, 0, 0]
  }
}`;

function parseComposition(source: string): HoloComposition {
  const result = parseHolo(source);
  expect(result.success).toBe(true);
  expect(result.errors ?? []).toEqual([]);
  expect(result.ast).toBeDefined();

  const ast = result.ast as HoloComposition;
  return {
    ...ast,
    objects: ast.objects ?? [],
    npcs: ast.npcs ?? [],
    domainBlocks: ast.domainBlocks ?? [],
  } as HoloComposition;
}

describe('agent brain as an ExportTarget', () => {
  it('classifies agent-inference through the _AssertNever-guarded target registry', () => {
    const target: ExportTarget = 'agent-inference';
    const daimonSeedTarget: ExportTarget = 'daimon-seed';

    expect(targetSovereignty(target)).toBe('bridge');
    expect(targetSovereignty(daimonSeedTarget)).toBe('bridge');
    expect(getRegisteredCompilerANSName('AgentInferenceCompiler')).toBe('agent-inference');
    expect(getRegisteredCompilerANSName('DaimonSeedCompiler')).toBe('daimon-seed');
    expect(getRegisteredCompilerANSName('WebGPUCompiler')).toBe('webgpu');
    expect(getRegisteredCompilerANSName('NIRCompiler')).toBe('nir');
  });

  it('compiles a .hsplus brain through the same ExportManager path as NIR and scene targets', async () => {
    const composition = parseComposition(AGENT_BRAIN_HSPLUS);
    const manager = new ExportManager({ useMemoryMonitoring: false, useFallback: false });

    try {
      const agentResult = await manager.export('agent-inference', composition, {
        useFallback: false,
        compilerOptions: { language: 'typescript' },
      });
      const daimonSeedResult = await manager.export('daimon-seed', composition, {
        useFallback: false,
        compilerOptions: {
          provenanceChainRef: 'prov:v2:test',
          emergenceContractRef: 'emergence:t4:test',
        },
      });
      const nirResult = await manager.export('nir', composition, { useFallback: false });
      const sceneResult = await manager.export('webgpu', composition, { useFallback: false });

      expect(agentResult.success).toBe(true);
      expect(agentResult.usedFallback).toBe(false);
      const agentFiles = agentResult.output as unknown as Record<string, string>;
      expect(agentFiles['agent.ts']).toContain('Generated by HoloScript AgentInferenceCompiler');
      expect(agentFiles['agent.ts']).toContain('Plan safely.');
      expect(agentFiles['config.json']).toContain('gpt-4o');

      expect(daimonSeedResult.success).toBe(true);
      expect(daimonSeedResult.usedFallback).toBe(false);
      expect(daimonSeedResult.output).toContain('"kind": "DaimonSeed"');
      expect(daimonSeedResult.output).toContain('ContentPolicyGate.jsonLogic');

      expect(nirResult.success).toBe(true);
      expect(nirResult.usedFallback).toBe(false);
      const nirGraph = readJson(nirResult.output as string) as {
        metadata: {
          generator: string;
          neuromorphicTraitsUsed: string[];
        };
      };
      expect(nirGraph.metadata.generator).toContain('NIRCompiler');
      expect(nirGraph.metadata.neuromorphicTraitsUsed).toContain('lif_neuron');

      expect(sceneResult.success).toBe(true);
      expect(sceneResult.usedFallback).toBe(false);
      expect(sceneResult.output).toContain('Object: planner_agent');
    } finally {
      manager.dispose();
    }
  });
});
