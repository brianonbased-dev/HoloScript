function objectsOf(composition: HoloComposition): HoloObjectDecl[] {
  return (composition.objects ?? []) as HoloObjectDecl[];
}

function traitsOf(obj: HoloObjectDecl): RuntimeTrait[] {
  return (obj.traits ?? []) as unknown as RuntimeTrait[];
}

function traitName(trait: RuntimeTrait): string {
  return typeof trait === 'string' ? trait : (trait.name ?? '');
}

function traitConfig(trait: RuntimeTrait | undefined): Record<string, unknown> {
  if (!trait || typeof trait === 'string') return {};
  return trait.config ?? trait.params ?? {};
}

function findTrait(obj: HoloObjectDecl, name: string): RuntimeTrait | undefined {
  return traitsOf(obj).find((trait) => traitName(trait) === name);
}

function hasAnyTrait(composition: HoloComposition, names: readonly string[]): boolean {
  return objectsOf(composition).some((obj) =>
    traitsOf(obj).some((trait) => names.includes(traitName(trait)))
  );
}

function collectUsedTraits(composition: HoloComposition, names: readonly string[]): string[] {
  const used = new Set<string>();
  for (const obj of objectsOf(composition)) {
    for (const trait of traitsOf(obj)) {
      const name = traitName(trait);
      if (names.includes(name)) used.add(name);
    }
  }
  return [...used].sort();
}

function numberConfig(
  config: Record<string, unknown>,
  keys: readonly string[],
  fallback: number
): number {
  for (const key of keys) {
    const raw = config[key];
    const numeric = typeof raw === 'number' ? raw : Number(raw);
    if (Number.isFinite(numeric)) return numeric;
  }
  return fallback;
}

function boolConfig(
  config: Record<string, unknown>,
  keys: readonly string[],
  fallback: boolean
): boolean {
  for (const key of keys) {
    const raw = config[key];
    if (typeof raw === 'boolean') return raw;
  }
  return fallback;
}

function floatLiteral(value: number): string {
  return `${Number.isInteger(value) ? value.toFixed(0) : value}f`;
}

function quotedKotlin(compiler: AndroidCompiler, value: unknown): string {
  return `"${compiler.escapeStringValue(String(value), 'Kotlin')}"`;
}

function emitHeader(
  compiler: AndroidCompiler,
  composition: HoloComposition,
  title: string,
  requirements: readonly string[]
): void {
  compiler.lines = [];
  compiler.indentLevel = 0;
  compiler.emit(`// Auto-generated by HoloScript AndroidCompiler - ${title}`);
  compiler.emit(
    `// Source: composition "${compiler.escapeStringValue(String(composition.name), 'Kotlin')}"`
  );
  for (const requirement of requirements) {
    compiler.emit(`// Requires ${requirement}`);
  }
  compiler.emit('// SceneView-native sidecar generated without legacy fragment or node factories.');
  compiler.emit('');
  compiler.emit(`package ${compiler.options.packageName}`);
  compiler.emit('');
}

function finish(compiler: AndroidCompiler): string {
  return `${compiler.lines.join('\n')}\n`;
}

function emitUsedTraits(compiler: AndroidCompiler, used: readonly string[]): void {
  if (used.length === 0) {
    compiler.emit('private val usedTraits = emptySet<String>()');
    return;
  }
  compiler.emit(`private val usedTraits = setOf(${used.map((trait) => `"${trait}"`).join(', ')})`);
}

