  compiler.emit('');
  compiler.emit(`class ${compiler.options.className}GeospatialVPSManager {`);
  compiler.indentLevel++;
  emitUsedTraits(compiler, collectUsedTraits(composition, GEOSPATIAL_TRAITS));
  compiler.emit('private var earth: Earth? = null');
  compiler.emit('private val geospatialAnchors = mutableMapOf<String, Anchor>()');
  compiler.emit(
    `private val horizontalAccuracyThreshold = ${GEOSPATIAL_DEFAULTS.vps.accuracyThreshold}.0`
  );
  compiler.emit(
    `private val headingAccuracyThreshold = ${GEOSPATIAL_DEFAULTS.vps.headingAccuracyThreshold}.0`
  );
  compiler.emit('');
  compiler.emit('fun setupGeospatialVPS(session: Session) {');
  compiler.indentLevel++;
  compiler.emit('val config = session.config');
  compiler.emit('config.geospatialMode = Config.GeospatialMode.ENABLED');
  if (compiler.compositionHasTrait(composition, 'geospatial_streetscape')) {
    compiler.emit('config.streetscapeGeometryMode = Config.StreetscapeGeometryMode.ENABLED');
  }
  compiler.emit('session.configure(config)');
  compiler.emit('earth = session.earth');
  compiler.indentLevel--;
  compiler.emit('}');
  compiler.emit('');
  compiler.emit('fun updateEarthTracking(session: Session) {');
  compiler.indentLevel++;
  compiler.emit('earth = session.earth');
  compiler.emit('val earthRef = earth ?: return');
  compiler.emit('if (earthRef.trackingState != TrackingState.TRACKING) return');
  compiler.emit('val geospatialState = earthRef.cameraGeospatialPose');
  compiler.emit('val horizontalAccuracy = geospatialState.horizontalAccuracy');
  compiler.emit('val headingAccuracy = geospatialState.headingAccuracy');
  compiler.emit(
    'if (horizontalAccuracy > horizontalAccuracyThreshold || headingAccuracy > headingAccuracyThreshold) return'
  );
  compiler.emit('Log.d("HoloScript", "cameraGeospatialPose localized")');
