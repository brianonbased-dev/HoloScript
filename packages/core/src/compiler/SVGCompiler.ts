/**
 * @fileoverview SVG Compiler (Scalable Vector Graphics)
 * @module @holoscript/core/compiler
 *
 * PURPOSE:
 * Compile HoloScript .holo compositions to Scalable Vector Graphics (SVG) format.
 * SOVEREIGN target — pure SVG XML output, no third-party engine required.
 *
 * Projection strategy: top-down orthographic view.
 *   SVG x  = world x * SCALE + ORIGIN_X
 *   SVG y  = world z * SCALE + ORIGIN_Y   (z is the horizontal depth axis)
 *   height = world y (vertical) is encoded via opacity / stroke-width hints
 *
 * Scale: 40 SVG pixels per world unit.  Origin: (400, 300) — centre of 800×600 viewport.
 */

// <!-- generated by HoloScript SVGCompiler -->

import type {
  HoloComposition,
  HoloObjectDecl,
  HoloObjectTrait,
  HoloSpatialGroup,
  HoloLight,
  HoloValue,
} from '../parser/HoloCompositionTypes.js';
import { CompilerBase, type CompilerToken } from './CompilerBase';
import { ANSCapabilityPath, type ANSCapabilityPathValue } from '@holoscript/core-types/ans';

// ─── Public API types ─────────────────────────────────────────────────────────

export interface SVGCompilerOptions {
  /** SVG viewport width in pixels (default: 800) */
  width?: number;
  /** SVG viewport height in pixels (default: 600) */
  height?: number;
  /** World-unit to SVG-pixel scale factor (default: 40) */
  scale?: number;
  /** Whether to pretty-print the SVG output with indentation (default: true) */
  pretty?: boolean;
  /** Include a background rect element (default: true) */
  background?: boolean;
  /** Background fill colour (default: '#1a1a2e') */
  backgroundColor?: string;
  /** Include radialGradient defs for lights (default: true) */
  renderLights?: boolean;
}

export type SVGCompilationResult = {
  svg: string;
  elements: number;
  groups: number;
};

// ─── Internal helpers ─────────────────────────────────────────────────────────

const SCALE = 40;
const ORIGIN_X = 400;
const ORIGIN_Y = 300;

/** Escape a raw string for safe embedding inside an SVG attribute value. */
function escapeAttr(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/'/g, '&apos;');
}

/** Escape a raw string for safe embedding inside SVG text content. */
function escapeText(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function toNumber(v: HoloValue | undefined, fallback: number): number {
  if (typeof v === 'number' && Number.isFinite(v)) return v;
  if (typeof v === 'string') {
    const n = parseFloat(v);
    if (Number.isFinite(n)) return n;
  }
  return fallback;
}

function toString(v: HoloValue | undefined, fallback: string): string {
  if (typeof v === 'string' && v.length > 0) return v;
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return fallback;
}

/**
 * Read a named object property from a HoloObjectDecl.
 * Properties are stored in the `properties` array as `{ key, value }` entries.
 */
function objProp(node: HoloObjectDecl, key: string): HoloValue | undefined {
  return node.properties.find((p) => p.key === key)?.value;
}

/**
 * Find a trait by name on a HoloObjectDecl (strips leading @ if present).
 */
function findTrait(node: HoloObjectDecl, name: string): HoloObjectTrait | undefined {
  const clean = name.startsWith('@') ? name.slice(1) : name;
  return node.traits.find((t) => {
    const tName = typeof t.name === 'string' ? t.name : String(t.name);
    return (tName.startsWith('@') ? tName.slice(1) : tName) === clean;
  });
}

/**
 * Extract the @color trait value, falling back to the `color` property, then to a default.
 */
function resolveColor(node: HoloObjectDecl, fallback: string): string {
  const colorTrait = findTrait(node, 'color');
  if (colorTrait) {
    const v = colorTrait.args?.[0] ?? colorTrait.config['value'] ?? colorTrait.config['color'];
    if (typeof v === 'string' && v.length > 0) return v;
  }
  const colorProp = objProp(node, 'color');
  return toString(colorProp, fallback);
}

/**
 * Project 3-D world coordinates onto the 2-D SVG top-down view.
 *   svgX = worldX * scale + originX
 *   svgY = worldZ * scale + originY   (depth maps to vertical axis)
 */
function projectX(worldX: number, scale: number, originX: number): number {
  return worldX * scale + originX;
}

function projectY(worldZ: number, scale: number, originY: number): number {
  return worldZ * scale + originY;
}

/**
 * Resolve position from a HoloObjectDecl.
 * The `position` field may be a HoloPosition object or live in `properties`.
 */
function resolvePosition(
  node: HoloObjectDecl
): { x: number; y: number; z: number } {
  // Prefer the typed position field when present
  if (node.position) {
    return {
      x: toNumber(node.position.x as HoloValue, 0),
      y: toNumber(node.position.y as HoloValue, 0),
      z: toNumber(node.position.z as HoloValue, 0),
    };
  }
  // Fall back to individual properties
  const posVal = objProp(node, 'position');
  if (posVal && typeof posVal === 'object' && !Array.isArray(posVal) && !('__bind' in posVal)) {
    const rec = posVal as Record<string, HoloValue>;
    return {
      x: toNumber(rec['x'], 0),
      y: toNumber(rec['y'], 0),
      z: toNumber(rec['z'], 0),
    };
  }
  if (Array.isArray(posVal)) {
    return {
      x: toNumber(posVal[0], 0),
      y: toNumber(posVal[1], 0),
      z: toNumber(posVal[2], 0),
    };
  }
  return { x: toNumber(objProp(node, 'x'), 0), y: toNumber(objProp(node, 'y'), 0), z: toNumber(objProp(node, 'z'), 0) };
}

/**
 * Resolve a uniform radius/size from a HoloObjectDecl for SVG sizing.
 * Checks `radius`, `size`, `width`, `scale` properties in order.
 */
function resolveRadius(node: HoloObjectDecl, scale: number): number {
  const r =
    toNumber(objProp(node, 'radius'), -1) !== -1
      ? toNumber(objProp(node, 'radius'), 0.5)
      : toNumber(objProp(node, 'size'), -1) !== -1
      ? toNumber(objProp(node, 'size'), 0.5)
      : toNumber(objProp(node, 'width'), -1) !== -1
      ? toNumber(objProp(node, 'width'), 0.5)
      : 0.5;
  // Also check node.scale.x if set
  if (node.scale) {
    const sx = toNumber(node.scale.x as HoloValue, 1);
    return r * sx * scale;
  }
  return r * scale;
}

function resolveWidthHeight(
  node: HoloObjectDecl,
  scale: number
): { w: number; h: number } {
  const w = toNumber(objProp(node, 'width'), toNumber(objProp(node, 'size'), 1));
  const h = toNumber(objProp(node, 'height'), toNumber(objProp(node, 'depth'), w));
  const sx = node.scale ? toNumber(node.scale.x as HoloValue, 1) : 1;
  const sz = node.scale ? toNumber(node.scale.z as HoloValue, 1) : 1;
  return { w: w * sx * scale, h: h * sz * scale };
}

// ─── Compiler class ───────────────────────────────────────────────────────────

export class SVGCompiler extends CompilerBase {
  protected readonly compilerName = 'SVGCompiler';

  protected override getRequiredCapability(): ANSCapabilityPathValue {
    return ANSCapabilityPath.COMPILE_SVG;
  }

  private opts!: Required<SVGCompilerOptions>;
  private elementCount = 0;
  private groupCount = 0;

  constructor(options: SVGCompilerOptions = {}) {
    super();
    this.applyOptions(options);
  }

  private applyOptions(options: SVGCompilerOptions): void {
    this.opts = {
      width: options.width ?? 800,
      height: options.height ?? 600,
      scale: options.scale ?? SCALE,
      pretty: options.pretty ?? true,
      background: options.background ?? true,
      backgroundColor: options.backgroundColor ?? '#1a1a2e',
      renderLights: options.renderLights ?? true,
    };
  }

  // ─── ICompiler.compile ────────────────────────────────────────────────

  override compile(
    composition: HoloComposition,
    agentToken: string,
    outputPath?: string
  ): SVGCompilationResult {
    this.validateCompilerAccess(agentToken as CompilerToken, outputPath);
    this.elementCount = 0;
    this.groupCount = 0;

    const { width, height } = this.opts;
    const originX = width / 2;
    const originY = height / 2;

    const lines: string[] = [];
    const indent = this.opts.pretty ? '  ' : '';
    const nl = this.opts.pretty ? '\n' : '';

    // Header comment
    lines.push('<!-- generated by HoloScript SVGCompiler -->');
    lines.push(
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">`
    );

    // ── <defs> — radialGradients for lights ──────────────────────────────
    const lights = composition.lights ?? [];
    if (this.opts.renderLights && lights.length > 0) {
      lines.push(`${indent}<defs>`);
      for (const light of lights) {
        lines.push(this.compileLightDef(light, indent + indent, originX, originY));
      }
      lines.push(`${indent}</defs>`);
    }

    // ── Background ───────────────────────────────────────────────────────
    if (this.opts.background) {
      lines.push(
        `${indent}<rect x="0" y="0" width="${width}" height="${height}" fill="${escapeAttr(this.opts.backgroundColor)}" />`
      );
    }

    // ── Light overlays (radialGradient fills) ────────────────────────────
    if (this.opts.renderLights && lights.length > 0) {
      for (const light of lights) {
        lines.push(this.compileLightOverlay(light, indent, originX, originY));
      }
    }

    // ── Spatial groups ───────────────────────────────────────────────────
    for (const group of composition.spatialGroups ?? []) {
      const groupLines = this.compileSpatialGroup(group, indent, originX, originY);
      lines.push(...groupLines);
    }

    // ── Top-level objects ────────────────────────────────────────────────
    for (const obj of composition.objects ?? []) {
      lines.push(this.compileObject(obj, indent, originX, originY));
    }

    lines.push('</svg>');

    const svg = lines.join(nl);
    return { svg, elements: this.elementCount, groups: this.groupCount };
  }

  // ─── Light → <radialGradient> def ────────────────────────────────────

  private compileLightDef(
    light: HoloLight,
    indent: string,
    originX: number,
    originY: number
  ): string {
    const id = escapeAttr(`light_${light.name.replace(/\W+/g, '_')}`);
    const colorProp = light.properties.find((p) => p.key === 'color')?.value;
    const color = toString(colorProp as HoloValue, '#ffffff');
    const intensityProp = light.properties.find((p) => p.key === 'intensity')?.value;
    const intensity = Math.min(1, Math.max(0, toNumber(intensityProp as HoloValue, 0.5)));
    const stopOpacity = (intensity * 0.4).toFixed(2);

    // Position from light properties
    const xProp = light.properties.find((p) => p.key === 'x')?.value;
    const zProp = light.properties.find((p) => p.key === 'z')?.value;
    const radiusProp = light.properties.find((p) => p.key === 'radius')?.value;
    const worldX = toNumber(xProp as HoloValue, 0);
    const worldZ = toNumber(zProp as HoloValue, 0);
    const cx = projectX(worldX, this.opts.scale, originX);
    const cy = projectY(worldZ, this.opts.scale, originY);
    const r = toNumber(radiusProp as HoloValue, 3) * this.opts.scale;

    return [
      `${indent}<radialGradient id="${id}" cx="${cx.toFixed(1)}" cy="${cy.toFixed(1)}" r="${r.toFixed(1)}" gradientUnits="userSpaceOnUse">`,
      `${indent}  <stop offset="0%" stop-color="${escapeAttr(color)}" stop-opacity="${stopOpacity}" />`,
      `${indent}  <stop offset="100%" stop-color="${escapeAttr(color)}" stop-opacity="0" />`,
      `${indent}</radialGradient>`,
    ].join(this.opts.pretty ? '\n' : '');
  }

  private compileLightOverlay(
    light: HoloLight,
    indent: string,
    originX: number,
    originY: number
  ): string {
    const id = escapeAttr(`light_${light.name.replace(/\W+/g, '_')}`);
    const xProp = light.properties.find((p) => p.key === 'x')?.value;
    const zProp = light.properties.find((p) => p.key === 'z')?.value;
    const radiusProp = light.properties.find((p) => p.key === 'radius')?.value;
    const worldX = toNumber(xProp as HoloValue, 0);
    const worldZ = toNumber(zProp as HoloValue, 0);
    const cx = projectX(worldX, this.opts.scale, originX);
    const cy = projectY(worldZ, this.opts.scale, originY);
    const r = toNumber(radiusProp as HoloValue, 3) * this.opts.scale;
    this.elementCount++;
    return `${indent}<circle cx="${cx.toFixed(1)}" cy="${cy.toFixed(1)}" r="${r.toFixed(1)}" fill="url(#${id})" data-holo-light="${escapeAttr(light.name)}" />`;
  }

  // ─── SpatialGroup → <g> ───────────────────────────────────────────────

  private compileSpatialGroup(
    group: HoloSpatialGroup,
    indent: string,
    originX: number,
    originY: number
  ): string[] {
    this.groupCount++;
    const gId = escapeAttr(group.id ?? group.name);
    const lines: string[] = [];
    lines.push(`${indent}<g id="${gId}" data-holo-group="${escapeAttr(group.name)}">`);

    // Child objects
    for (const obj of group.objects ?? []) {
      lines.push(this.compileObject(obj, indent + '  ', originX, originY));
    }

    // Nested groups
    for (const nested of group.groups ?? []) {
      lines.push(...this.compileSpatialGroup(nested, indent + '  ', originX, originY));
    }

    lines.push(`${indent}</g>`);
    return lines;
  }

  // ─── HoloObjectDecl → SVG element ─────────────────────────────────────

  private compileObject(
    node: HoloObjectDecl,
    indent: string,
    originX: number,
    originY: number
  ): string {
    this.elementCount++;
    const pos = resolvePosition(node);
    const svgX = projectX(pos.x, this.opts.scale, originX);
    const svgY = projectY(pos.z, this.opts.scale, originY);
    const fill = resolveColor(node, '#4a9eff');
    const label = escapeAttr(node.name);
    const dataAttr = `data-holo-object="${label}"`;

    // Derive the primitive type from the `type` object property or the name heuristic
    const typeProp = toString(objProp(node, 'type'), '').toLowerCase();
    const nameLower = node.name.toLowerCase();

    const shapeHint =
      typeProp ||
      (nameLower.includes('sphere') || nameLower.includes('ball') || nameLower.includes('orb')
        ? 'sphere'
        : nameLower.includes('box') || nameLower.includes('cube') || nameLower.includes('wall')
        ? 'box'
        : nameLower.includes('cylinder') || nameLower.includes('column') || nameLower.includes('pillar')
        ? 'cylinder'
        : nameLower.includes('plane') || nameLower.includes('floor') || nameLower.includes('ground')
        ? 'plane'
        : nameLower.includes('text') || nameLower.includes('label') || nameLower.includes('sign')
        ? 'text'
        : 'unknown');

    switch (shapeHint) {
      case 'sphere':
        return this.compileSphere(node, svgX, svgY, fill, indent, dataAttr);

      case 'box':
      case 'cube':
        return this.compileBox(node, svgX, svgY, fill, indent, dataAttr);

      case 'cylinder':
        return this.compileCylinder(node, svgX, svgY, fill, indent, dataAttr);

      case 'plane':
      case 'floor':
      case 'ground':
        return this.compilePlane(node, svgX, svgY, fill, indent, dataAttr);

      case 'text':
        return this.compileText(node, svgX, svgY, fill, indent, dataAttr);

      default:
        return this.compileUnknown(node, svgX, svgY, fill, indent, dataAttr);
    }
  }

  // ─── Shape emitters ──────────────────────────────────────────────────

  private compileSphere(
    node: HoloObjectDecl,
    cx: number,
    cy: number,
    fill: string,
    indent: string,
    dataAttr: string
  ): string {
    const r = resolveRadius(node, this.opts.scale);
    return `${indent}<circle cx="${cx.toFixed(1)}" cy="${cy.toFixed(1)}" r="${r.toFixed(1)}" fill="${escapeAttr(fill)}" ${dataAttr} />`;
  }

  private compileBox(
    node: HoloObjectDecl,
    cx: number,
    cy: number,
    fill: string,
    indent: string,
    dataAttr: string
  ): string {
    const { w, h } = resolveWidthHeight(node, this.opts.scale);
    const x = (cx - w / 2).toFixed(1);
    const y = (cy - h / 2).toFixed(1);
    return `${indent}<rect x="${x}" y="${y}" width="${w.toFixed(1)}" height="${h.toFixed(1)}" fill="${escapeAttr(fill)}" ${dataAttr} />`;
  }

  private compileCylinder(
    node: HoloObjectDecl,
    cx: number,
    cy: number,
    fill: string,
    indent: string,
    dataAttr: string
  ): string {
    const rx = resolveRadius(node, this.opts.scale);
    const ryProp = toNumber(objProp(node, 'depth'), -1);
    const ry = ryProp >= 0 ? ryProp * this.opts.scale : rx * 0.4;
    return `${indent}<ellipse cx="${cx.toFixed(1)}" cy="${cy.toFixed(1)}" rx="${rx.toFixed(1)}" ry="${ry.toFixed(1)}" fill="${escapeAttr(fill)}" ${dataAttr} />`;
  }

  private compilePlane(
    node: HoloObjectDecl,
    cx: number,
    cy: number,
    fill: string,
    indent: string,
    dataAttr: string
  ): string {
    const { w, h } = resolveWidthHeight(node, this.opts.scale);
    const x = (cx - w / 2).toFixed(1);
    const y = (cy - h / 2).toFixed(1);
    return `${indent}<rect x="${x}" y="${y}" width="${w.toFixed(1)}" height="${h.toFixed(1)}" fill="${escapeAttr(fill)}" opacity="0.3" ${dataAttr} />`;
  }

  private compileText(
    node: HoloObjectDecl,
    x: number,
    y: number,
    fill: string,
    indent: string,
    dataAttr: string
  ): string {
    const content = toString(objProp(node, 'text') ?? objProp(node, 'value') ?? objProp(node, 'label'), node.name);
    const fontSize = toNumber(objProp(node, 'fontSize') ?? objProp(node, 'font_size') ?? objProp(node, 'size'), 14);
    return `${indent}<text x="${x.toFixed(1)}" y="${y.toFixed(1)}" fill="${escapeAttr(fill)}" font-size="${fontSize}" text-anchor="middle" dominant-baseline="middle" ${dataAttr}>${escapeText(content)}</text>`;
  }

  private compileUnknown(
    node: HoloObjectDecl,
    cx: number,
    cy: number,
    fill: string,
    indent: string,
    dataAttr: string
  ): string {
    // Unknown types rendered as dashed rect to signal unrecognised shape
    const { w, h } = resolveWidthHeight(node, this.opts.scale);
    const x = (cx - w / 2).toFixed(1);
    const y = (cy - h / 2).toFixed(1);
    return `${indent}<rect x="${x}" y="${y}" width="${w.toFixed(1)}" height="${h.toFixed(1)}" fill="none" stroke="${escapeAttr(fill)}" stroke-dasharray="4 2" ${dataAttr} />`;
  }
}

export default SVGCompiler;
