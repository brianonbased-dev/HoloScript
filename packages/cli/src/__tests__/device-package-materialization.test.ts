import { describe, expect, it } from 'vitest';

import { materializeDevicePackage } from '../device-package-materialization';

const SOURCE = `composition "Public Holon Node" {
  metadata { version: "0.1.0" }
  object "Node Runtime" {
    role: "owned_edge_agent"
    health_endpoint: "/health"
  }
}`;

describe('compiler-born device package materialization', () => {
  it('materializes a deterministic rootless Jetson source bundle', () => {
    const first = materializeDevicePackage({
      sourcePath: 'public-holon-node.holo',
      source: SOURCE,
      device: 'jetson-orin',
      compilerVersion: '8.0.13',
    });
    const second = materializeDevicePackage({
      sourcePath: 'public-holon-node.holo',
      source: SOURCE,
      device: 'jetson-orin',
      compilerVersion: '8.0.13',
    });

    expect(first).toEqual(second);
    expect(first.receipt).toMatchObject({
      schema: 'holoscript-device-package-materialization/v0.1.0',
      phase: 'source-materialized',
      profileId: 'jetson-orin',
      compiler: {
        name: 'NodeServiceCompiler',
        classification: 'bridge',
        sourceCompiled: true,
      },
    });
    expect(first.files['app/index.ts']).toContain(
      'Auto-generated by HoloScript NodeServiceCompiler'
    );
    expect(first.files['app/Dockerfile']).toContain('FROM node:20-alpine');
    expect(first.files['packaging/systemd/user/holonode.service']).toContain(
      'NoNewPrivileges=true'
    );
    expect(first.files['packaging/systemd/user/holonode.service']).not.toContain('User=root');
    expect(first.files['source/public-holon-node.holo']).toBe(SOURCE);
    expect(first.receipt.files.every((file) => /^[a-f0-9]{64}$/.test(file.sha256))).toBe(true);
    expect(first.receipt.gates).toEqual([
      { id: 'born-from-holoscript', status: 'passed' },
      { id: 'device-profile', status: 'passed' },
      { id: 'reproducible-build', status: 'required' },
      { id: 'platform-security', status: 'required' },
      { id: 'physical-device', status: 'required' },
      { id: 'cold-public-consumer', status: 'required' },
      { id: 'upgrade-rollback', status: 'required' },
    ]);
  });

  it('materializes the generic ARM64 profile without Jetson-only claims', () => {
    const bundle = materializeDevicePackage({
      sourcePath: 'public-holon-node.holo',
      source: SOURCE,
      device: 'linux-arm64',
      compilerVersion: '8.0.13',
    });

    expect(bundle.receipt.profileId).toBe('linux-arm64');
    expect(bundle.files['packaging/device-profile.json']).not.toContain('tensorrt');
  });

  it('materializes Android through its compiler without root or signing custody', () => {
    const bundle = materializeDevicePackage({
      sourcePath: 'public-holon-node.holo',
      source: SOURCE,
      device: 'android-arm64',
      compilerVersion: '8.0.13',
    });

    expect(bundle.receipt).toMatchObject({
      profileId: 'android-arm64',
      compiler: {
        name: 'AndroidCompiler',
        classification: 'bridge',
        sourceCompiled: true,
      },
    });
    expect(bundle.files['app/src/main/java/dev/holoscript/holonode/HoloNodeActivity.kt']).toContain(
      'class HoloNodeActivity'
    );
    expect(bundle.files['app/src/main/AndroidManifest.xml']).toContain('uses-permission');
    expect(bundle.files['settings.gradle.kts']).toContain('dependencyResolutionManagement');
    expect(bundle.files['packaging/android-admission.json']).toContain('"rootRequired": false');
    expect(bundle.files['packaging/android-admission.json']).toContain(
      '"signingCredentialBundled": false'
    );
    const deliveredText = JSON.stringify(bundle.files).toLowerCase();
    const forbiddenCustodyMarkers = [
      'holomesh_wallet',
      '.env',
      ['begin', 'private', 'key'].join(' '),
      ['key', 'store'].join(''),
    ];
    for (const marker of forbiddenCustodyMarkers) {
      expect(deliveredText).not.toContain(marker);
    }
  });
});
