#!/usr/bin/env tsx
/**
 * HoloScript Studio — .holo Page Compiler
 *
 * Compiles .holo files from holo-pages/ into Next.js App Router pages in src/app/.
 * Maintains .holo-manifest.json to track generated vs hand-written files.
 *
 * Usage:
 *   pnpm holo:build          # one-shot compile
 *   pnpm holo:build --watch  # watch mode for dev
 *   pnpm holo:check          # --strict --check: compile AND compare, writing nothing
 *
 * WHY --check EXISTS, AND WHY THIS GENERATOR FORMATS ITS OWN OUTPUT
 *
 * Measured 2026-09-21 on a clean checkout of main: --strict alone, with no source
 * change, rewrote 12 committed pages and the manifest. Nothing had drifted in
 * meaning -- the generator emits double-quoted redirects and four blank lines, while
 * the committed copies carry single quotes and none, because 8b0f3a850 (2026-07-28)
 * ran a repo-wide prettier pass over files whose first line says DO NOT EDIT.
 *
 * So --strict was answering a different question than its name promised. It asks
 * "does every .holo still compile"; a tree can be perfectly compilable and still
 * ship committed output that no longer matches its source. --check asks that second
 * question, and holo:check now runs both.
 *
 * The generator formats through the prettier API before it writes, so its output and
 * the committed copy are the same bytes and a real change is legible in the diff.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from 'fs';
import { join, relative, dirname, extname } from 'path';
import { format, resolveConfig } from 'prettier';
import { parseHolo } from '../../core/src/parser/HoloCompositionParser';
import { NextJSCompiler } from '../../core/src/compiler/NextJSCompiler';

const STUDIO_ROOT = join(import.meta.dirname || __dirname, '..');
const HOLO_PAGES_DIR = join(STUDIO_ROOT, 'holo-pages');
const APP_DIR = join(STUDIO_ROOT, 'src', 'app');
const MANIFEST_PATH = join(STUDIO_ROOT, '.holo-manifest.json');

const GENERATED_HEADER = '// @generated by HoloScript NextJSCompiler — DO NOT EDIT\n';

/** --check: regenerate into memory and COMPARE. Writes nothing. */
const CHECK = process.argv.includes('--check');
const drift: string[] = [];

/**
 * Format one generated artifact, then write it (build) or compare it against the
 * committed copy (--check). Both modes consume the identical bytes, so the check
 * cannot drift away from the build it is guarding.
 *
 * Prettier is applied through the API rather than the CLI because .prettierignore
 * excludes some generated paths whose committed form IS formatted.
 */
async function emitFile(target: string, code: string): Promise<void> {
  const config = await resolveConfig(target);
  let pretty = code;
  try {
    pretty = await format(code, { ...config, filepath: target });
  } catch {
    // A page prettier cannot parse is a compiler bug, not a formatting one. Keep the
    // raw bytes so the real error surfaces downstream rather than being masked here.
    pretty = code;
  }

  if (CHECK) {
    let current: string | null = null;
    try {
      current = readFileSync(target, 'utf-8');
    } catch {
      current = null;
    }
    if (current !== pretty) drift.push(relative(STUDIO_ROOT, target));
    return;
  }

  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, pretty, 'utf-8');
}

/**
 * Pages that must go through Vector2DCompiler (pnpm vector:build), NOT NextJSCompiler.
 * Relative to holo-pages/, using forward slashes. compile-holo-pages.ts skips these so
 * a bare `pnpm holo:build` does not overwrite Vector2D-generated output with empty divs.
 */
const VECTOR_PAGES = new Set(['agent-ability/page.holo']);

const SLOT_IMPORTS = {
  PipelineWorkbench: {
    component: 'PipelineWorkbench',
    importPath: '@/components/pipeline/PipelineWorkbench',
  },
  // The canonical R3F + @react-three/xr viewer — a native .holo page mounts it with a
  // `sceneName` (loaded from examples/) and optional `agentId` (embodied AgentAvatar).
  // Phase A (founder 2026-06-14 "consume the canonical pipeline"): this replaced the
  // bespoke raw-three.js ImmersiveViewer so the live pages render through the canonical
  // R3FCompiler → R3F renderer + shared xr-embodiment rig, not a hand-authored substitute.
  ImmersiveScene: {
    component: 'WebXRViewer',
    importPath: '@/embed/WebXRViewer',
  },
} as const;

// =============================================================================
// MANIFEST
// =============================================================================

interface Manifest {
  generatedFiles: string[];
  lastBuild: string;
}

function loadManifest(): Manifest {
  if (existsSync(MANIFEST_PATH)) {
    return JSON.parse(readFileSync(MANIFEST_PATH, 'utf-8'));
  }
  return { generatedFiles: [], lastBuild: '' };
}

/** Exactly the bytes the build writes, with the wall-clock stamp neutralised. */
function manifestBytes(m: Manifest, lastBuild: string): string {
  return JSON.stringify({ ...m, lastBuild }, null, 2) + '\n';
}

async function saveManifest(manifest: Manifest, errorCount = 0): Promise<void> {
  if (CHECK) {
    // EVERYTHING EXCEPT THE STAMP, and the file's shape too.
    //
    // The stamp genuinely cannot be byte-stable -- it is wall-clock -- so it is
    // neutralised rather than compared. But this used to compare ONLY
    // `generatedFiles`, which left every other key, every value, and the file's
    // whole serialisation unchecked: a junk key, a garbage lastBuild and the
    // file rewritten as one line with no trailing newline all passed. Comparing
    // the bytes the writer WOULD produce catches all of it and still ignores
    // time passing.
    let committedRaw: string | null = null;
    try {
      committedRaw = readFileSync(MANIFEST_PATH, 'utf-8');
    } catch {
      committedRaw = null;
    }
    if (committedRaw === null) {
      drift.push(`${relative(STUDIO_ROOT, MANIFEST_PATH)} (missing)`);
      return;
    }
    let committed: Manifest;
    try {
      committed = JSON.parse(committedRaw) as Manifest;
    } catch {
      drift.push(`${relative(STUDIO_ROOT, MANIFEST_PATH)} (not valid JSON)`);
      return;
    }
    // A partial run cannot speak to the file list; say nothing rather than a red
    // that only means "a page failed", which is already reported above.
    if (errorCount > 0) return;
    const stamp = typeof committed.lastBuild === 'string' ? committed.lastBuild : '';
    if (manifestBytes(manifest, stamp) !== committedRaw) {
      drift.push(`${relative(STUDIO_ROOT, MANIFEST_PATH)}`);
    }
    return;
  }

  writeFileSync(MANIFEST_PATH, manifestBytes(manifest, manifest.lastBuild));
}

// =============================================================================
// FILE DISCOVERY
// =============================================================================

function findHoloFiles(dir: string): string[] {
  const results: string[] = [];
  if (!existsSync(dir)) return results;

  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      results.push(...findHoloFiles(full));
    } else if (extname(entry) === '.holo') {
      results.push(full);
    }
  }

  return results;
}

// =============================================================================
// COMPILATION
// =============================================================================

async function compileFile(holoPath: string): Promise<{ outputPath: string; code: string } | null> {
  const source = readFileSync(holoPath, 'utf-8');
  const relPath = relative(HOLO_PAGES_DIR, holoPath);

  // Parse
  const parseResult = parseHolo(source);
  if (!parseResult.success || !parseResult.ast) {
    console.error(`  ✗ Parse error in ${relPath}:`);
    for (const err of parseResult.errors) {
      // @ts-expect-error - compatibility
      console.error(`    Line ${err.line}: ${err.message}`);
    }
    return null;
  }

  // Compile to Next.js
  const compiler = new NextJSCompiler({ slots: SLOT_IMPORTS });
  // Local page generation uses CompilerBase's dev-mode bypass; production callers must pass credentials.
  const result = await compiler.compile(parseResult.ast, '');

  // Determine output path: holo-pages/pipeline/page.holo → src/app/pipeline/page.tsx
  const dirPart = dirname(relPath);
  const outputPath = join(APP_DIR, dirPart, 'page.tsx');

  const generatedCode = result.code.startsWith('// @generated')
    ? result.code
    : GENERATED_HEADER + result.code;
  const normalizedCode = generatedCode.replace(/[ \t]+$/gm, '');

  return {
    outputPath,
    code: normalizedCode.endsWith('\n') ? normalizedCode : `${normalizedCode}\n`,
  };
}

async function build(): Promise<void> {
  const startTime = Date.now();
  const holoFiles = findHoloFiles(HOLO_PAGES_DIR);

  if (holoFiles.length === 0) {
    console.log('No .holo files found in holo-pages/');
    return;
  }

  console.log(`Compiling ${holoFiles.length} .holo page(s)...`);

  const manifest = loadManifest();
  const newGeneratedFiles: string[] = [];
  let successCount = 0;
  let errorCount = 0;

  for (const holoPath of holoFiles) {
    const relPath = relative(HOLO_PAGES_DIR, holoPath).replace(/\\/g, '/');
    // Skip pages owned by the Vector2DCompiler (pnpm vector:build handles these).
    if (VECTOR_PAGES.has(relPath)) {
      console.log(`  ↷ ${relPath} — skipped (vector page; run \`pnpm vector:build\`)`);
      continue;
    }
    const result = await compileFile(holoPath);

    if (!result) {
      errorCount++;
      continue;
    }

    // Safety check: don't overwrite hand-written files
    //
    // NORMALISED, because this string is PERSISTED into .holo-manifest.json and
    // then compared against a fresh run. `relative()` returns the platform
    // separator, so a manifest written on Windows carries "src\\app\\x\\page.tsx"
    // and the same 15 pages on Linux or macOS produce "src/app/x/page.tsx" --
    // not one entry matches, the check reports drift on a byte-clean tree, and
    // since pre-push began running this check that is a permanent block on every
    // non-Windows seat. `relPath` two dozen lines up was already normalised for
    // exactly this reason; this line was missed.
    const relOutput = relative(STUDIO_ROOT, result.outputPath).replace(/\\/g, '/');
    if (existsSync(result.outputPath)) {
      const existing = readFileSync(result.outputPath, 'utf-8');
      if (!existing.startsWith('// @generated') && !manifest.generatedFiles.includes(relOutput)) {
        console.error(`  ⚠ Skipping ${relOutput} — hand-written file (not in manifest)`);
        errorCount++;
        continue;
      }
    }

    // Write output — or, under --check, compare it and leave the file alone
    await emitFile(result.outputPath, result.code);
    newGeneratedFiles.push(relOutput);
    successCount++;
    console.log(`  ✓ ${relPath} → ${relOutput}`);
  }

  // THE MANIFEST IS A PURE FUNCTION OF THE SOURCES, not an append-only log.
  //
  // This was `[...new Set([...manifest.generatedFiles, ...newGeneratedFiles])]`:
  // it started from the COMMITTED list and only ever added. The --check
  // comparison then held committed against committed-union-fresh, which differs
  // only when something is ADDED -- so deleting a page .holo left its generated
  // src/app/<route>/page.tsx shipping, kept the stale manifest entry, and the
  // check said OK. A reorder was invisible for the same reason. Measured:
  // deleting four page sources left the check green.
  //
  // Only when the run was COMPLETE, though. A failed page is absent from
  // newGeneratedFiles, and pruning on a partial run would both lose the record
  // and make an already-generated file look hand-written to the safety check
  // above on the next run.
  if (errorCount === 0) {
    manifest.generatedFiles = [...new Set(newGeneratedFiles)].sort();
  } else {
    manifest.generatedFiles = [...new Set([...manifest.generatedFiles, ...newGeneratedFiles])];
  }
  manifest.lastBuild = new Date().toISOString();
  await saveManifest(manifest, errorCount);

  const elapsed = Date.now() - startTime;
  console.log(`\nDone: ${successCount} compiled, ${errorCount} errors (${elapsed}ms)`);
  if (errorCount > 0) {
    // Fail-soft by default so a single malformed .holo cannot kill the whole
    // Studio deploy. `prebuild` runs this in the deploy build (Railway) where
    // `next dev` never ran it locally — a frontmatter typo on main would
    // otherwise take down ALL of Studio, not the one page (premortem 2026-05-31,
    // "most dangerous failure"). Last-good generated output is kept; the broken
    // page just isn't regenerated. `--strict` (HOLO_STRICT=1) is what makes the
    // regression fail before main rather than on the deploy build -- but only if
    // somebody runs it. Measured 2026-09-21: nothing does. There is no HoloCI gate
    // wired to this, and .github/workflows/ holds only _archived/.
    const STRICT = process.argv.includes('--strict') || process.env.HOLO_STRICT === '1';
    const msg = `holo:build: ${errorCount} .holo page(s) did not compile`;
    if (STRICT) {
      throw new Error(`${msg} (strict mode — failing the gate)`);
    }
    console.warn(
      `\n⚠ ${msg} — keeping last-good generated output; deploy NOT blocked.\n` +
        `  Nothing runs this for you: pnpm check:studio-generators, by hand, before you push.`
    );
  }

  if (CHECK) {
    if (drift.length > 0) {
      console.error('');
      console.error(
        `holo:check FAILED -- ${drift.length} generated file(s) differ from what this generator emits:`
      );
      for (const f of drift) console.error(`    ${f}`);
      console.error('');
      console.error('  The committed output is stale or was hand-edited.');
      console.error('  Fix: pnpm run holo:build, then commit the result.');
      console.error('  Never edit a @generated file directly -- change the .holo source.');
      throw new Error(`holo:check: ${drift.length} generated file(s) out of date`);
    }
    console.log(
      `holo:check OK -- ${successCount} page(s): committed output matches the generator.`
    );
  }
}

// =============================================================================
// WATCH MODE
// =============================================================================

async function watch(): Promise<void> {
  console.log('Watching holo-pages/ for changes...');

  // Initial build
  await build();

  // Dynamic import chokidar (dev dependency)
  const { watch: chokidarWatch } = await import('chokidar');
  const watcher = chokidarWatch(join(HOLO_PAGES_DIR, '**/*.holo'), {
    ignoreInitial: true,
    awaitWriteFinish: { stabilityThreshold: 300 },
  });

  watcher.on('change', async (path) => {
    console.log(`\n[holo:watch] ${relative(STUDIO_ROOT, path)} changed`);
    const result = await compileFile(path);
    if (result) {
      mkdirSync(dirname(result.outputPath), { recursive: true });
      writeFileSync(result.outputPath, result.code);
      console.log(`  ✓ Recompiled`);
    }
  });

  watcher.on('add', (path) => {
    console.log(`\n[holo:watch] New file: ${relative(STUDIO_ROOT, path)}`);
    void build(); // Rebuild all to update manifest
  });
}

// =============================================================================
// CLI
// =============================================================================

const isWatch = process.argv.includes('--watch');

if (isWatch) {
  watch().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
} else {
  build().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
