#!/usr/bin/env tsx
/**
 * HoloScript Studio — .holo Page Compiler
 *
 * Compiles .holo files from holo-pages/ into Next.js App Router pages in src/app/.
 * Maintains .holo-manifest.json to track generated vs hand-written files.
 *
 * Usage:
 *   pnpm holo:build          # one-shot compile
 *   pnpm holo:build --watch  # watch mode for dev
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from 'fs';
import { join, relative, dirname, extname } from 'path';
import { parseHolo } from '../../core/src/parser/HoloCompositionParser';
import { NextJSCompiler } from '../../core/src/compiler/NextJSCompiler';

const STUDIO_ROOT = join(import.meta.dirname || __dirname, '..');
const HOLO_PAGES_DIR = join(STUDIO_ROOT, 'holo-pages');
const APP_DIR = join(STUDIO_ROOT, 'src', 'app');
const MANIFEST_PATH = join(STUDIO_ROOT, '.holo-manifest.json');

const GENERATED_HEADER = '// @generated by HoloScript NextJSCompiler — DO NOT EDIT\n';
const SLOT_IMPORTS = {
  PipelineWorkbench: {
    component: 'PipelineWorkbench',
    importPath: '@/components/pipeline/PipelineWorkbench',
  },
  // The canonical R3F + @react-three/xr viewer — a native .holo page mounts it with a
  // `sceneName` (loaded from examples/) and optional `agentId` (embodied AgentAvatar).
  // Phase A (founder 2026-06-14 "consume the canonical pipeline"): this replaced the
  // bespoke raw-three.js ImmersiveViewer so the live pages render through the canonical
  // R3FCompiler → R3F renderer + shared xr-embodiment rig, not a hand-authored substitute.
  ImmersiveScene: {
    component: 'WebXRViewer',
    importPath: '@/embed/WebXRViewer',
  },
} as const;

// =============================================================================
// MANIFEST
// =============================================================================

interface Manifest {
  generatedFiles: string[];
  lastBuild: string;
}

function loadManifest(): Manifest {
  if (existsSync(MANIFEST_PATH)) {
    return JSON.parse(readFileSync(MANIFEST_PATH, 'utf-8'));
  }
  return { generatedFiles: [], lastBuild: '' };
}

function saveManifest(manifest: Manifest): void {
  writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2) + '\n');
}

// =============================================================================
// FILE DISCOVERY
// =============================================================================

function findHoloFiles(dir: string): string[] {
  const results: string[] = [];
  if (!existsSync(dir)) return results;

  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      results.push(...findHoloFiles(full));
    } else if (extname(entry) === '.holo') {
      results.push(full);
    }
  }

  return results;
}

// =============================================================================
// COMPILATION
// =============================================================================

async function compileFile(holoPath: string): Promise<{ outputPath: string; code: string } | null> {
  const source = readFileSync(holoPath, 'utf-8');
  const relPath = relative(HOLO_PAGES_DIR, holoPath);

  // Parse
  const parseResult = parseHolo(source);
  if (!parseResult.success || !parseResult.ast) {
    console.error(`  ✗ Parse error in ${relPath}:`);
    for (const err of parseResult.errors) {
      // @ts-expect-error - compatibility
      console.error(`    Line ${err.line}: ${err.message}`);
    }
    return null;
  }

  // Compile to Next.js
  const compiler = new NextJSCompiler({ slots: SLOT_IMPORTS });
  // Local page generation uses CompilerBase's dev-mode bypass; production callers must pass credentials.
  const result = await compiler.compile(parseResult.ast, '');

  // Determine output path: holo-pages/pipeline/page.holo → src/app/pipeline/page.tsx
  const dirPart = dirname(relPath);
  const outputPath = join(APP_DIR, dirPart, 'page.tsx');

  const generatedCode = result.code.startsWith('// @generated')
    ? result.code
    : GENERATED_HEADER + result.code;
  const normalizedCode = generatedCode.replace(/[ \t]+$/gm, '');

  return {
    outputPath,
    code: normalizedCode.endsWith('\n') ? normalizedCode : `${normalizedCode}\n`,
  };
}

async function build(): Promise<void> {
  const startTime = Date.now();
  const holoFiles = findHoloFiles(HOLO_PAGES_DIR);

  if (holoFiles.length === 0) {
    console.log('No .holo files found in holo-pages/');
    return;
  }

  console.log(`Compiling ${holoFiles.length} .holo page(s)...`);

  const manifest = loadManifest();
  const newGeneratedFiles: string[] = [];
  let successCount = 0;
  let errorCount = 0;

  for (const holoPath of holoFiles) {
    const relPath = relative(HOLO_PAGES_DIR, holoPath);
    const result = await compileFile(holoPath);

    if (!result) {
      errorCount++;
      continue;
    }

    // Safety check: don't overwrite hand-written files
    const relOutput = relative(STUDIO_ROOT, result.outputPath);
    if (existsSync(result.outputPath)) {
      const existing = readFileSync(result.outputPath, 'utf-8');
      if (!existing.startsWith('// @generated') && !manifest.generatedFiles.includes(relOutput)) {
        console.error(`  ⚠ Skipping ${relOutput} — hand-written file (not in manifest)`);
        errorCount++;
        continue;
      }
    }

    // Write output
    mkdirSync(dirname(result.outputPath), { recursive: true });
    writeFileSync(result.outputPath, result.code);
    newGeneratedFiles.push(relOutput);
    successCount++;
    console.log(`  ✓ ${relPath} → ${relOutput}`);
  }

  // Update manifest
  manifest.generatedFiles = [...new Set([...manifest.generatedFiles, ...newGeneratedFiles])];
  manifest.lastBuild = new Date().toISOString();
  saveManifest(manifest);

  const elapsed = Date.now() - startTime;
  console.log(`\nDone: ${successCount} compiled, ${errorCount} errors (${elapsed}ms)`);
  if (errorCount > 0) {
    // Fail-soft by default so a single malformed .holo cannot kill the whole
    // Studio deploy. `prebuild` runs this in the deploy build (Railway) where
    // `next dev` never ran it locally — a frontmatter typo on main would
    // otherwise take down ALL of Studio, not the one page (premortem 2026-05-31,
    // "most dangerous failure"). Last-good generated output is kept; the broken
    // page just isn't regenerated. The HoloCI gate runs `--strict` (HOLO_STRICT=1)
    // so the regression fails BEFORE main, never on the deploy build.
    const STRICT = process.argv.includes('--strict') || process.env.HOLO_STRICT === '1';
    const msg = `holo:build: ${errorCount} .holo page(s) did not compile`;
    if (STRICT) {
      throw new Error(`${msg} (strict mode — failing the gate)`);
    }
    console.warn(
      `\n⚠ ${msg} — keeping last-good generated output; deploy NOT blocked.\n` +
        `  Run \`pnpm holo:check\` (--strict) in CI to fail on this before main.`
    );
  }
}

// =============================================================================
// WATCH MODE
// =============================================================================

async function watch(): Promise<void> {
  console.log('Watching holo-pages/ for changes...');

  // Initial build
  await build();

  // Dynamic import chokidar (dev dependency)
  const { watch: chokidarWatch } = await import('chokidar');
  const watcher = chokidarWatch(join(HOLO_PAGES_DIR, '**/*.holo'), {
    ignoreInitial: true,
    awaitWriteFinish: { stabilityThreshold: 300 },
  });

  watcher.on('change', async (path) => {
    console.log(`\n[holo:watch] ${relative(STUDIO_ROOT, path)} changed`);
    const result = await compileFile(path);
    if (result) {
      mkdirSync(dirname(result.outputPath), { recursive: true });
      writeFileSync(result.outputPath, result.code);
      console.log(`  ✓ Recompiled`);
    }
  });

  watcher.on('add', (path) => {
    console.log(`\n[holo:watch] New file: ${relative(STUDIO_ROOT, path)}`);
    void build(); // Rebuild all to update manifest
  });
}

// =============================================================================
// CLI
// =============================================================================

const isWatch = process.argv.includes('--watch');

if (isWatch) {
  watch().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
} else {
  build().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
