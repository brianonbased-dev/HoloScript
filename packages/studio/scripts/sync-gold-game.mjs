#!/usr/bin/env node
/**
 * Sync the gold-game build artifacts into Studio's public/ tree.
 *
 * The game lives in examples/gold-game/ (44 GATE receipts of invested work,
 * frozen behind "no Studio route" — /capabilities 2026-06-10, D.081 Studio =
 * operate surface). The production image ships only packages/, and
 * Dockerfile copies packages/studio/public wholesale, so public/ is the
 * zero-config path for the 2.4MB self-contained game artifact.
 *
 * Copies:
 *   examples/gold-game/drive-build/index.html -> public/gold-game/index.html
 *   examples/gold-game/2d-build/index.html    -> public/gold-game/2d/index.html
 *   examples/gold-game/*receipt*.json         -> public/gold-game/receipts/
 * and writes public/gold-game/receipts/manifest.json (name, bytes, sha256).
 *
 * NEVER hand-edit the game artifact — it is generated by drive-build.mjs
 * (GATES.md documents the stale-artifact gotcha). Re-run this script after
 * any regeneration.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const studioRoot = path.resolve(here, '..');
const repoRoot = path.resolve(studioRoot, '..', '..');
const gameDir = path.join(repoRoot, 'examples', 'gold-game');
const outDir = path.join(studioRoot, 'public', 'gold-game');

if (!fs.existsSync(gameDir)) {
  console.error(`[sync-gold-game] source missing: ${gameDir}`);
  process.exit(2);
}

fs.mkdirSync(path.join(outDir, 'receipts'), { recursive: true });
fs.mkdirSync(path.join(outDir, '2d'), { recursive: true });

const copies = [
  [path.join(gameDir, 'drive-build', 'index.html'), path.join(outDir, 'index.html')],
  [path.join(gameDir, '2d-build', 'index.html'), path.join(outDir, '2d', 'index.html')],
];
for (const [src, dst] of copies) {
  if (!fs.existsSync(src)) {
    console.error(`[sync-gold-game] missing artifact: ${src}`);
    process.exit(2);
  }
  fs.copyFileSync(src, dst);
  console.log(
    `[sync-gold-game] ${path.relative(repoRoot, src)} -> ${path.relative(studioRoot, dst)} (${fs.statSync(dst).size} bytes)`
  );
}

const receiptFiles = fs
  .readdirSync(gameDir)
  .filter((f) => f.toLowerCase().includes('receipt') && f.endsWith('.json'))
  .sort();

const manifest = [];
for (const f of receiptFiles) {
  const src = path.join(gameDir, f);
  const dst = path.join(outDir, 'receipts', f);
  const buf = fs.readFileSync(src);
  fs.writeFileSync(dst, buf);
  manifest.push({
    name: f,
    bytes: buf.length,
    sha256: crypto.createHash('sha256').update(buf).digest('hex'),
  });
}
fs.writeFileSync(
  path.join(outDir, 'receipts', 'manifest.json'),
  JSON.stringify(
    { generatedAt: new Date().toISOString(), count: manifest.length, receipts: manifest },
    null,
    2
  )
);
console.log(`[sync-gold-game] ${manifest.length} receipts + manifest.json`);
