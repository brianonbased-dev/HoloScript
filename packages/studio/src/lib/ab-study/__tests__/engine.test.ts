/**
 * Invariant tests for the blind A/B study engine.
 *
 * Must prove:
 * 1. Provenance is hidden from the rater.
 * 2. Order is randomized per trial.
 * 3. Statistical aggregation is correct (binomial + Wilson CI).
 */

import { describe, it, expect } from 'vitest';
import {
  stripProvenance,
  createTrial,
  recordChoice,
  aggregateResults,
  type ABTrial,
} from '../engine';

describe('stripProvenance', () => {
  it('removes block comments', () => {
    const raw = '/* model: LSC-v3 */\nscene { }';
    expect(stripProvenance(raw)).not.toContain('/*');
    expect(stripProvenance(raw)).not.toContain('LSC-v3');
  });

  it('removes line comments', () => {
    const raw = '// generated by baseline\nscene { }';
    expect(stripProvenance(raw)).not.toContain('//');
    expect(stripProvenance(raw)).not.toContain('baseline');
  });

  it('removes @generated / @source / @author / @timestamp', () => {
    const raw = `@generated 2026-05-25
@source lsc
@author claude
@timestamp 123
scene { }`;
    const clean = stripProvenance(raw);
    expect(clean).not.toContain('@generated');
    expect(clean).not.toContain('@source');
    expect(clean).not.toContain('@author');
    expect(clean).not.toContain('@timestamp');
  });

  it('preserves structural code', () => {
    const raw = 'scene { node { transform 1 0 0 } }';
    expect(stripProvenance(raw)).toBe(raw);
  });
});

describe('createTrial', () => {
  it('produces both left-lsc and right-lsc over many trials', () => {
    const lsc = '/* lsc */ scene A';
    const base = '/* baseline */ scene B';
    let leftCount = 0;
    const n = 200;
    for (let i = 0; i < n; i++) {
      const t = createTrial('prompt', lsc, base);
      if (t.lscSide === 'left') leftCount++;
      // Provenance must be stripped in both positions
      expect(t.left.holoSource).not.toContain('lsc');
      expect(t.left.holoSource).not.toContain('baseline');
      expect(t.right.holoSource).not.toContain('lsc');
      expect(t.right.holoSource).not.toContain('baseline');
    }
    // With n=200, P(leftCount < 70 or > 130) ≈ 0.0001 — practically impossible
    expect(leftCount).toBeGreaterThanOrEqual(70);
    expect(leftCount).toBeLessThanOrEqual(130);
  });

  it('assigns unique trial IDs', () => {
    const ids = new Set(Array.from({ length: 50 }, () => createTrial('p', 'a', 'b').trialId));
    expect(ids.size).toBe(50);
  });
});

describe('recordChoice', () => {
  it('records choice and strength', () => {
    const t = createTrial('p', 'a', 'b');
    const r = recordChoice(t, 'left', 4);
    expect(r.chosenSide).toBe('left');
    expect(r.strength).toBe(4);
    expect(r.recordedAt).toMatch(/^\d{4}-/);
  });

  it('rejects double-recording', () => {
    const t = createTrial('p', 'a', 'b');
    const r = recordChoice(t, 'left', 3);
    expect(() => recordChoice(r, 'right', 5)).toThrow('already has a recorded choice');
  });

  it('rejects out-of-range strength', () => {
    const t = createTrial('p', 'a', 'b');
    expect(() => recordChoice(t, 'left', 0)).toThrow('1–5');
    expect(() => recordChoice(t, 'left', 6)).toThrow('1–5');
  });
});

describe('aggregateResults', () => {
  it('returns zeroed result for no completed trials', () => {
    const r = aggregateResults([]);
    expect(r.trialCount).toBe(0);
    expect(r.passesGate).toBe(false);
    expect(r.binomialP).toBe(1);
  });

  it('computes exact binomial + Wilson CI for 30/40 preference', () => {
    // 40 trials, 30 LSC wins → rate 0.75
    const trials: ABTrial[] = Array.from({ length: 40 }, (_, i) => {
      const t = createTrial('p', 'a', 'b');
      // Force LSC win on first 30
      return recordChoice(t, i < 30 ? t.lscSide : t.lscSide === 'left' ? 'right' : 'left', 3);
    });
    const r = aggregateResults(trials);
    expect(r.trialCount).toBe(40);
    expect(r.lscWins).toBe(30);
    expect(r.baselineWins).toBe(10);
    expect(r.preferenceRate).toBeCloseTo(0.75, 4);
    expect(r.ci95[0]).toBeCloseTo(0.598, 3); // Wilson lower bound for 30/40
    expect(r.ci95[1]).toBeLessThan(0.9); // upper bound ~0.858
    expect(r.passesGate).toBe(false); // 0.598 < 0.65
    expect(r.binomialP).toBeLessThan(0.005);
  });

  it('passes gate at n=100 with 75% preference', () => {
    const trials: ABTrial[] = Array.from({ length: 100 }, (_, i) => {
      const t = createTrial('p', 'a', 'b');
      return recordChoice(t, i < 75 ? t.lscSide : t.lscSide === 'left' ? 'right' : 'left', 3);
    });
    const r = aggregateResults(trials);
    expect(r.preferenceRate).toBeCloseTo(0.75, 4);
    expect(r.ci95[0]).toBeGreaterThanOrEqual(0.65);
    expect(r.passesGate).toBe(true);
  });

  it('fails gate when preference is only 55%', () => {
    const trials: ABTrial[] = Array.from({ length: 40 }, (_, i) => {
      const t = createTrial('p', 'a', 'b');
      return recordChoice(t, i < 22 ? t.lscSide : t.lscSide === 'left' ? 'right' : 'left', 3);
    });
    const r = aggregateResults(trials);
    expect(r.preferenceRate).toBeCloseTo(0.55, 4);
    expect(r.passesGate).toBe(false);
  });
});
