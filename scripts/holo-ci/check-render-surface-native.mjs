#!/usr/bin/env node
/**
 * check-render-surface-native.mjs — freeze the production render surface to HS-native.
 *
 * WHY THIS GATE EXISTS (render-surface dogfooding ruling, 2026-06-05):
 *   Doctrine (D.012 light-dogfood live / heavy not yet, D.014, I.018): the rendering and
 *   engine surface that ships to Railway production should be authored in native HoloScript
 *   (.hs/.hsplus/.holo) and emitted by a compiler — not hand-written React/Three.js .tsx —
 *   with the only exception being compiler EXAMPLES (fixtures / golden outputs / stories /
 *   tests). Reality at ruling time: r3f-renderer is 100% hand-authored React/Three.js (0
 *   generated); studio is ~680 .tsx with only ~10 compiler-generated from .holo. The full
 *   ban is therefore NOT a present-tense state — it is a FREEZE RATCHET:
 *
 *     • Existing hand-authored render .tsx is GRANDFATHERED into an explicit allowlist
 *       (seeded once via --update). It is legacy surface to be migrated, not new debt.
 *     • Any NEW render .tsx under the production roots must EITHER carry a compiler
 *       generation header (it was emitted from .hs) OR be a compiler example (path-excluded)
 *       OR be deliberately added to the allowlist on purpose. Net-new hand-authored render
 *       is blocked by default.
 *     • As compilers mature (panel @slot bodies, an .hs→Three.js render-component compiler),
 *       migrated files gain a generation header and drop OUT of the allowlist — the allowlist
 *       shrinks toward zero. That burn-down IS the heavy-dogfood direction; this gate measures
 *       it (an allowlisted file that now carries a header is reported as MIGRATED-CAN-PRUNE).
 *
 *   This is Level A (convention) of a two-level design. The generation header is a string
 *   convention and therefore forgeable; Level B (a later ratchet) tightens it into a
 *   verifiable provenance round-trip (re-derive sha256(compile(source.hs)) via the
 *   conformance PackageProvenance.sourceHash model). Level A ships first and never blocks on
 *   Level B — a forgeable-but-shipping freeze beats a tamper-proof-but-unshipped one while
 *   the .tsx surface keeps growing.
 *
 * WHAT IT DOES (read-only, no install, no network):
 *   - Walks each production render root (default: packages/r3f-renderer/src, packages/studio/src).
 *   - Collects every .tsx EXCEPT compiler examples (path contains __tests__/fixtures/examples,
 *     or basename matches *.test/*.spec/*.stories/*.example.tsx) — those are the legitimate
 *     exception and are always allowed.
 *   - For each candidate:
 *       • carries a generation header in the first HEADER_SCAN_LINES lines  -> OK (compiler-emitted)
 *       • else path is in the allowlist                                     -> OK (grandfathered legacy)
 *       • else                                                              -> ERROR (net-new hand-authored render)
 *   - Reconciliation: an allowlist entry no longer present -> SURFACE-SHRANK (reconcile via --update);
 *     an allowlist entry that now has a header -> MIGRATED-CAN-PRUNE (informational; prune via --update).
 *
 * Generation header grammar (canonical + tolerant): a line in the file head matching
 *   /@generated by HoloScript/i   (e.g. Native2DCompiler.ts, NextJSCompiler — the live emitters)
 *   or /@holoscript-generated/i   (the forward-looking superset token Level B will carry a sourceHash on)
 *
 * Usage:
 *   node scripts/holo-ci/check-render-surface-native.mjs           # check, exit 1 on drift
 *   node scripts/holo-ci/check-render-surface-native.mjs --update  # (re)seed allowlist from current
 *                                                                   # hand-authored surface (intentional)
 *   node scripts/holo-ci/check-render-surface-native.mjs --root <dir>
 *   node scripts/holo-ci/check-render-surface-native.mjs --roots packages/r3f-renderer/src,packages/studio/src
 *
 * Exit 0 iff every render .tsx is generated, an example, or allowlisted. Exit 1 on drift. Exit 2 on usage.
 */

import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import { join, relative, basename, sep } from 'node:path';

const args = process.argv.slice(2);
const UPDATE = args.includes('--update');
const rootIdx = args.indexOf('--root');
const ROOT = rootIdx >= 0 ? args[rootIdx + 1] : process.cwd();
const rootsIdx = args.indexOf('--roots');
const RENDER_ROOTS = (rootsIdx >= 0 ? args[rootsIdx + 1] : 'packages/r3f-renderer/src,packages/studio/src')
  .split(',')
  .map((s) => s.trim())
  .filter(Boolean);

const ALLOWLIST = join(ROOT, 'scripts', 'holo-ci', 'render-surface-native-allowlist.json');

// First N lines of a file are scanned for the generation header (compilers emit it at the top,
// usually line 1, occasionally after a leading directive like "use client"; 6 is generous).
const HEADER_SCAN_LINES = 6;
const HEADER = /@generated by HoloScript|@holoscript-generated/i;

// Compiler EXAMPLES — the only legitimate exception. Always allowed, never allowlisted.
const EXAMPLE_DIR = /(^|[\\/])(__tests__|__fixtures__|fixtures|examples|__mocks__|stories|__stories__)([\\/]|$)/i;
const EXAMPLE_FILE = /\.(test|spec|stories|story|example|fixture|mock)\.tsx$/i;

function toPosix(p) {
  return p.split(sep).join('/');
}

function isExample(relPath) {
  return EXAMPLE_DIR.test(relPath) || EXAMPLE_FILE.test(basename(relPath));
}

function hasHeader(absPath) {
  let head;
  try {
    head = readFileSync(absPath, 'utf8').split('\n', HEADER_SCAN_LINES + 1).slice(0, HEADER_SCAN_LINES).join('\n');
  } catch {
    return false;
  }
  return HEADER.test(head);
}

function walkTsx(dirAbs, acc) {
  let entries;
  try {
    entries = readdirSync(dirAbs, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const abs = join(dirAbs, e.name);
    if (e.isDirectory()) {
      if (e.name === 'node_modules' || e.name === 'dist' || e.name === '.next' || e.name === 'build') continue;
      walkTsx(abs, acc);
    } else if (e.isFile() && e.name.endsWith('.tsx')) {
      acc.push(abs);
    }
  }
}

// ── Gather candidates across all render roots ────────────────────────────────
const presentRoots = [];
const missingRoots = [];
for (const r of RENDER_ROOTS) {
  const abs = join(ROOT, r);
  if (existsSync(abs) && statSync(abs).isDirectory()) presentRoots.push(abs);
  else missingRoots.push(r);
}
if (presentRoots.length === 0) {
  console.error(`[render-surface] no render roots present under ${ROOT} (looked for: ${RENDER_ROOTS.join(', ')})`);
  process.exit(2);
}
for (const r of missingRoots) {
  console.error(`[render-surface] note: render root absent (skipped): ${r}`);
}

const candidates = []; // { rel, abs, generated, example }
for (const rootAbs of presentRoots) {
  const files = [];
  walkTsx(rootAbs, files);
  for (const abs of files) {
    const rel = toPosix(relative(ROOT, abs));
    candidates.push({ rel, abs, example: isExample(rel), generated: hasHeader(abs) });
  }
}

// Files that must be accounted for = render .tsx that are neither examples nor compiler-generated.
const handAuthored = candidates.filter((c) => !c.example && !c.generated).map((c) => c.rel).sort();

// ── --update: (re)seed the grandfather allowlist from current hand-authored surface ──
if (UPDATE) {
  writeFileSync(
    ALLOWLIST,
    JSON.stringify(
      {
        _comment:
          'FREEZE RATCHET allowlist (D.012/D.014). Grandfathered hand-authored render .tsx under the production roots. ' +
          'A NEW render .tsx may only be added here on purpose; the goal is to SHRINK this list toward zero by migrating ' +
          'files to .hs-authored compiler output (which carries an "@generated by HoloScript" header and drops out automatically). ' +
          'Regenerate with: node scripts/holo-ci/check-render-surface-native.mjs --update',
        roots: RENDER_ROOTS,
        headerHint: 'Compiler-emitted files carry "@generated by HoloScript <Compiler>" in their first 6 lines and need NOT be listed.',
        allow: handAuthored,
      },
      null,
      2
    ) + '\n'
  );
  console.log(
    `[render-surface] allowlist seeded: ${handAuthored.length} grandfathered hand-authored render .tsx -> ${ALLOWLIST}`
  );
  const genCount = candidates.filter((c) => c.generated).length;
  const exCount = candidates.filter((c) => c.example).length;
  console.log(`[render-surface] (also present: ${genCount} compiler-generated, ${exCount} compiler-example .tsx — not listed)`);
  process.exit(0);
}

// ── check mode ───────────────────────────────────────────────────────────────
let allow = { allow: [] };
if (existsSync(ALLOWLIST)) {
  try {
    allow = JSON.parse(readFileSync(ALLOWLIST, 'utf8'));
  } catch {
    console.error(`[render-surface] ALLOWLIST unparseable: ${ALLOWLIST}`);
    process.exit(1);
  }
} else {
  console.error(`[render-surface] ALLOWLIST missing: ${ALLOWLIST} — run --update to create it`);
  process.exit(1);
}
const allowSet = new Set(allow.allow || []);
const presentRelSet = new Set(candidates.map((c) => c.rel));

const errors = [];
const notes = [];

// (1) net-new hand-authored render .tsx not grandfathered -> block
for (const rel of handAuthored) {
  if (!allowSet.has(rel)) {
    errors.push(
      `SURFACE-GREW  ${rel} — net-new hand-authored render .tsx. Author it in .hs and compile it (so it carries an ` +
        `"@generated by HoloScript" header), make it a compiler example, or — if intentionally hand-authored legacy — add it via --update.`
    );
  }
}

// (2) allowlist hygiene: entries that moved/migrated
for (const rel of allow.allow || []) {
  if (!presentRelSet.has(rel)) {
    errors.push(`SURFACE-SHRANK  ${rel} is allowlisted but no longer present (removed/renamed/moved) — reconcile via --update`);
  } else {
    const c = candidates.find((x) => x.rel === rel);
    if (c && c.generated) {
      notes.push(`MIGRATED-CAN-PRUNE  ${rel} now carries a generation header — migrated to HS-native; prune from allowlist via --update`);
    }
  }
}

const genCount = candidates.filter((c) => c.generated).length;
const exCount = candidates.filter((c) => c.example).length;
const legacyCount = handAuthored.length;

if (notes.length) {
  console.log(`[render-surface] ${notes.length} migrated file(s) can be pruned from the allowlist:`);
  for (const n of notes) console.log('  ' + n);
}

if (errors.length) {
  console.error(`[render-surface] ${errors.length} issue(s):`);
  for (const e of errors) console.error('  ' + e);
  console.error(
    `\n[render-surface] FREEZE: production render surface must be HS-native (compiler-emitted) or a compiler example. ` +
      `Hand-authored legacy is grandfathered; net-new hand-authored render is blocked. Roots: ${RENDER_ROOTS.join(', ')}.`
  );
  process.exit(1);
}

console.log(
  `[render-surface] OK — ${genCount} compiler-generated, ${exCount} examples, ${legacyCount} grandfathered legacy (allowlisted); ` +
    `0 net-new hand-authored render .tsx. Roots: ${RENDER_ROOTS.join(', ')}.`
);
process.exit(0);
