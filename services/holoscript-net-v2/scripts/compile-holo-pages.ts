#!/usr/bin/env tsx
/**
 * holoscript.net v2 — .holo Page Compiler
 *
 * Compiles .holo files from holo-pages/ into Next.js App Router pages in
 * src/app/. This is the dogfood: the front door is authored in HoloScript and
 * compiled to web by HoloScript's own NextJSCompiler. @slot islands (the R3F
 * pink blob, live widgets) are declared inline in the .holo and self-register
 * their imports.
 *
 * Mirrors packages/studio/scripts/compile-holo-pages.ts.
 *
 * Usage:
 *   pnpm holo:build          # one-shot compile
 *   pnpm holo:build --watch  # watch mode for dev
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from 'fs';
import { join, relative, dirname, extname } from 'path';
import { parseHolo } from '../../../packages/core/src/parser/HoloCompositionParser';
import { NextJSCompiler } from '../../../packages/core/src/compiler/NextJSCompiler';

const SERVICE_ROOT = join(import.meta.dirname || __dirname, '..');
const HOLO_PAGES_DIR = join(SERVICE_ROOT, 'holo-pages');
const APP_DIR = join(SERVICE_ROOT, 'src', 'app');
const MANIFEST_PATH = join(SERVICE_ROOT, '.holo-manifest.json');

const GENERATED_HEADER = '// @generated by HoloScript NextJSCompiler — DO NOT EDIT\n';

interface Manifest {
  generatedFiles: string[];
  lastBuild: string;
}

function loadManifest(): Manifest {
  if (existsSync(MANIFEST_PATH)) {
    return JSON.parse(readFileSync(MANIFEST_PATH, 'utf-8'));
  }
  return { generatedFiles: [], lastBuild: '' };
}

function saveManifest(manifest: Manifest): void {
  writeFileSync(MANIFEST_PATH, JSON.stringify(manifest, null, 2) + '\n');
}

function findHoloFiles(dir: string): string[] {
  const results: string[] = [];
  if (!existsSync(dir)) return results;

  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      results.push(...findHoloFiles(full));
    } else if (extname(entry) === '.holo') {
      results.push(full);
    }
  }
  return results;
}

async function compileFile(holoPath: string): Promise<{ outputPath: string; code: string } | null> {
  const source = readFileSync(holoPath, 'utf-8');
  const relPath = relative(HOLO_PAGES_DIR, holoPath);

  const parseResult = parseHolo(source);
  if (!parseResult.success || !parseResult.ast) {
    console.error(`  ✗ Parse error in ${relPath}:`);
    for (const err of parseResult.errors) {
      // @ts-expect-error - error shape compatibility
      console.error(`    Line ${err.line}: ${err.message}`);
    }
    return null;
  }

  // Local page generation uses CompilerBase's dev-mode bypass; production
  // callers must pass credentials. Slots are declared inline in the .holo.
  const compiler = new NextJSCompiler();
  const result = await compiler.compile(parseResult.ast, '');

  const dirPart = dirname(relPath);
  const outputPath = join(APP_DIR, dirPart, 'page.tsx');

  const generatedCode = result.code.startsWith('// @generated')
    ? result.code
    : GENERATED_HEADER + result.code;
  const normalizedCode = generatedCode.replace(/[ \t]+$/gm, '');

  return { outputPath, code: normalizedCode.endsWith('\n') ? normalizedCode : `${normalizedCode}\n` };
}

async function build(): Promise<void> {
  const holoFiles = findHoloFiles(HOLO_PAGES_DIR);

  if (holoFiles.length === 0) {
    console.log('No .holo files found in holo-pages/');
    return;
  }

  console.log(`Compiling ${holoFiles.length} .holo page(s)...`);

  const manifest = loadManifest();
  const newGeneratedFiles: string[] = [];
  let successCount = 0;
  let errorCount = 0;

  for (const holoPath of holoFiles) {
    const relPath = relative(HOLO_PAGES_DIR, holoPath);
    const result = await compileFile(holoPath);

    if (!result) {
      errorCount++;
      continue;
    }

    const relOutput = relative(SERVICE_ROOT, result.outputPath);
    if (existsSync(result.outputPath)) {
      const existing = readFileSync(result.outputPath, 'utf-8');
      if (!existing.startsWith('// @generated') && !manifest.generatedFiles.includes(relOutput)) {
        console.error(`  ⚠ Skipping ${relOutput} — hand-written file (not in manifest)`);
        errorCount++;
        continue;
      }
    }

    mkdirSync(dirname(result.outputPath), { recursive: true });
    writeFileSync(result.outputPath, result.code);
    newGeneratedFiles.push(relOutput);
    successCount++;
    console.log(`  ✓ ${relPath} → ${relOutput}`);
  }

  manifest.generatedFiles = [...new Set([...manifest.generatedFiles, ...newGeneratedFiles])];
  manifest.lastBuild = new Date().toISOString();
  saveManifest(manifest);

  console.log(`\nDone: ${successCount} compiled, ${errorCount} errors`);
  if (errorCount > 0) {
    throw new Error(`holo:build failed: ${errorCount} .holo page(s) did not compile`);
  }
}

async function watch(): Promise<void> {
  console.log('Watching holo-pages/ for changes...');
  await build();

  const { watch: chokidarWatch } = await import('chokidar');
  const watcher = chokidarWatch(join(HOLO_PAGES_DIR, '**/*.holo'), {
    ignoreInitial: true,
    awaitWriteFinish: { stabilityThreshold: 300 },
  });

  watcher.on('change', async (path: string) => {
    console.log(`\n[holo:watch] ${relative(SERVICE_ROOT, path)} changed`);
    const result = await compileFile(path);
    if (result) {
      mkdirSync(dirname(result.outputPath), { recursive: true });
      writeFileSync(result.outputPath, result.code);
      console.log(`  ✓ Recompiled`);
    }
  });

  watcher.on('add', () => void build());
}

const isWatch = process.argv.includes('--watch');

if (isWatch) {
  watch().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
} else {
  build().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
